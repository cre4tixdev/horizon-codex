import { expect, test } from '@playwright/test'

test('Calendrier : couleurs partagées, périodes compactes et absence de débordement', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.route('**/api/horizon/calendar/events?*', async (route) => {
    const start = new Date(Date.parse(new URL(route.request().url()).searchParams.get('from')!) + 86400000).toISOString()
    await route.fulfill({ json: { periods: [], items: ['publication', 'submission', 'visit', 'hearing', 'result', 'inventory'].map((kind) => ({ id: `fixture-${kind}`, source_module: 'crm', source_entity: 'crm_opportunities', source_record_id: '123456789abcdef', kind, title: 'Un événement avec une description très longue pour vérifier la largeur des cellules', code: '00003', company: 'Client calendrier', start, end: '', all_day: true, timezone: 'Europe/Paris', location: '', href: '/crm/opportunities/123456789abcdef' })) } })
  })
  await page.route('**/api/collections/crm_appointment_kinds/records?*', (route) => route.fulfill({ json: { page: 1, perPage: 500, totalItems: 2, totalPages: 1, items: [{ id: 'visit', code: 'visit', label: 'Visite', color: '#0D9488', tone: 'blue', active: true, sort_order: 1 }, { id: 'hearing', code: 'hearing', label: 'Soutenance', color: '#9333EA', tone: 'violet', active: true, sort_order: 2 }] } }))
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  await page.goto('/calendar')
  const periods = page.getByRole('group', { name: 'Période du calendrier', exact: true })
  await expect(periods.getByRole('button', { name: 'Mois', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.calendar-event[data-kind=visit]')).toHaveCSS('--tag-color', '#0D9488')
  await expect(page.locator('.calendar-legend span', { hasText: 'Visite' })).toHaveCSS('--tag-color', '#0D9488')
  await expect(page.locator('.calendar-event[data-kind=hearing]')).toHaveCSS('--tag-color', '#9333EA')
  for (const [label, count] of [['Semaine', 1], ['Mois', 1], ['Trimestre', 3], ['Année', 12]] as const) {
    await periods.getByRole('button', { name: label, exact: true }).click()
    await expect(periods.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.locator('.calendar-month')).toHaveCount(count)
    await expect(page.locator('.calendar-event')).toHaveCount(6)
    for (const width of [1440, 960, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect(await page.locator('.calendar-event').evaluateAll((elements) => elements.every((element) => element.getBoundingClientRect().right <= element.closest('.calendar-day')!.getBoundingClientRect().right))).toBe(true)
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    if (label === 'Trimestre' || label === 'Année') await page.screenshot({ path: `/private/tmp/horizon-calendar-${count}.png`, fullPage: true })
  }
  const selectedMonth = page.locator('.calendar-month-link').nth(5)
  const monthLabel = await selectedMonth.innerText()
  await selectedMonth.focus()
  await page.keyboard.press('Enter')
  await expect(periods.getByRole('button', { name: 'Mois', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.calendar-month')).toHaveCount(1)
  await expect(page.locator('.calendar-toolbar strong')).toContainText(monthLabel.toLocaleLowerCase('fr-FR'))
  await periods.getByRole('button', { name: 'Année', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0, 700))
  const navigationBounds = (await page.locator('.calendar-navigation').boundingBox())!
  const topbarBounds = (await page.locator('.topbar').boundingBox())!
  expect(Math.abs(navigationBounds.y - topbarBounds.y - topbarBounds.height)).toBeLessThan(2)
  await expect(page.locator('.calendar-legend')).toBeInViewport()
  await expect(periods).toBeInViewport()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-calendar-dark.png', fullPage: true })
})

test('Calendrier : créer, modifier et retirer un événement manuel', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  await page.goto('/calendar')
  await expect(page.getByRole('button', { name: 'Ajouter un événement', exact: true })).toBeVisible()
  const chosenDate = await page.locator('.calendar-day[data-date]').nth(4).getAttribute('data-date')
  await page.locator(`.calendar-day[data-date="${chosenDate}"] .calendar-day-add`).click()
  const editor = page.getByRole('dialog', { name: 'Nouvel événement', exact: true })
  await expect(editor.getByLabel('Date', { exact: true })).toHaveValue(chosenDate!)
  await editor.getByLabel('Toute la journée', { exact: true }).uncheck()
  await expect(editor.getByLabel('Début', { exact: true })).toHaveValue(`${chosenDate}T09:00`)
  await editor.getByLabel('Toute la journée', { exact: true }).check()
  await expect(editor.getByLabel('Date', { exact: true })).toHaveValue(chosenDate!)
  await editor.getByLabel('Titre', { exact: true }).fill('Préparer le chantier')
  await expect(editor.getByRole('combobox', { name: 'Visibilité de l’événement', exact: true })).toHaveText('Personnel')
  await editor.getByLabel('Toute la journée', { exact: true }).check()
  const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Paris', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date())
  await editor.getByLabel('Date', { exact: true }).fill(today)
  await editor.getByLabel('Lieu ou lien', { exact: true }).fill('Meudon')
  await editor.getByLabel('Notes', { exact: true }).fill('Vérifier les accès au chantier')
  await editor.getByRole('radio', { name: 'Turquoise', exact: true }).check()
  await page.screenshot({ path: '/private/tmp/horizon-calendar-manual-editor.png', fullPage: true })
  await editor.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(editor).toHaveCount(0)
  const item = page.locator('.calendar-event', { hasText: 'Préparer le chantier' })
  await expect(item).toHaveCSS('--tag-color', '#0D9488')
  await page.goto('/')
  await expect(page.locator('.dashboard-agenda')).toContainText('Préparer le chantier')
  await page.goto('/calendar')
  await page.reload()
  await expect(item).toBeVisible()
  await item.click()
  await expect(page).toHaveURL(/event=[a-z0-9]{15}/)
  const details = page.getByRole('dialog', { name: 'Événement du calendrier', exact: true })
  await expect(details.getByLabel('Notes', { exact: true })).toHaveValue('Vérifier les accès au chantier')
  await details.getByLabel('Titre', { exact: true }).fill('Préparer le chantier modifié')
  await details.getByRole('combobox', { name: 'Visibilité de l’événement', exact: true }).click()
  await page.getByRole('option', { name: 'Équipe', exact: true }).click()
  await details.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(details).toHaveCount(0)
  await expect(page).not.toHaveURL(/event=/)
  await page.locator('.calendar-event', { hasText: 'Préparer le chantier modifié' }).click()
  await details.getByRole('button', { name: 'Supprimer l’événement', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Supprimer', exact: true }).click()
  await expect(details).toHaveCount(0)
  await expect(page.locator('.calendar-event', { hasText: 'Préparer le chantier' })).toHaveCount(0)
})

