import { expect, test } from '@playwright/test'

test('Coûts du devis : comparatif, sélection, marge, application puis sauvegarde explicite', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1100 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid'); await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!'); await page.getByRole('button', { name: 'Se connecter', exact: true }).click(); await expect(page).toHaveURL('/')
  const headers = { Authorization: await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '') }, base = 'http://127.0.0.1:18090/api/'
  const post = async (path: string, data: object) => { const response = await request.post(base + path, { headers, data }); const result = await response.json(); expect(response.ok(), JSON.stringify(result)).toBe(true); return result }
  const get = async (path: string) => (await request.get(base + path, { headers })).json()
  const session = await post('collections/core_users/auth-refresh', {})
  const company = await post('collections/contacts_companies/records', { name: 'Client actualisation coûts', active: true })
  const stages = await get('collections/crm_stages/records')
  const opportunity = await post('horizon/crm/save', { creation_key: crypto.randomUUID(), input: { title: 'Affaire coûts', company: company.id, contact: '', owner: session.record.id, stage: stages.items[0].id, type: 'direct', estimated_value: 100, estimated_cost: 0, currency: 'EUR', probability: 0, expected_date: '2026-12-31', description: '', status: 'open', market_types: [] } })
  const categories = (await get('horizon/inventory/categories')).items, units = (await get('collections/inventory_units/records')).items
  const productInput = { sku: 'REFRESH-COST', name: 'Produit à actualiser', description: 'Produit à actualiser', category: categories.find((item: { code: string }) => item.code === 'supplies').id, base_unit: units.find((item: { code: string }) => item.code === 'm').id, kind: 'consumable', sale_enabled: true, purchase_enabled: true, stock_policy: 'stocked', replenishment_policy: 'manual', tracking: 'none', manufacturer: 'BELDEN', manufacturer_ref: 'REFRESH', barcode: '', variant_group: '', reference_cost: 100, sale_currency: 'EUR', offers: [] }
  let product = await post('horizon/inventory/products/save', { creation_key: crypto.randomUUID(), input: productInput })
  const line = await post('horizon/inventory/quote-line', { product: product.id, offer: 'reference', currency: 'EUR' })
  const quote = await post('horizon/sales/quotes/save', { creation_key: crypto.randomUUID(), input: { opportunity: opportunity.id, title: 'Devis actualisation', quote_date: '2026-10-21', valid_until: '2026-11-21', notes: '', lines: [{ ...line, quantity: 2, price_source: 'margin' }, { ...line, description: 'Coût personnalisé', quantity: 1, unit_cost: 105, unit_price: 200, price_source: 'manual' }] } })
  const changeCost = async (value: number) => { product = await post('horizon/inventory/products/save', { id: product.id, updated: product.updated, input: { ...productInput, reference_cost: value } }) }
  await page.goto('/sales/quotes/' + quote.id)
  const cost = page.getByLabel('Coût ligne 1', { exact: true }), price = page.getByLabel('Prix unitaire ligne 1', { exact: true })
  await expect(cost).toBeVisible()
  const refreshLine = page.getByRole('button', { name: 'Actualiser le coût ligne 1', exact: true })
  expect(Number(await refreshLine.evaluate((node) => getComputedStyle(node).opacity))).toBeGreaterThan(0)
  const refreshAll = page.getByRole('button', { name: 'Actualiser les coûts', exact: true })
  await expect(page.locator('th[data-column-key="unit_cost"]').getByRole('button', { name: 'Actualiser les coûts', exact: true })).toBeVisible()
  const headerButton = (await refreshAll.boundingBox())!, rowButton = (await refreshLine.boundingBox())!
  expect(Math.abs(headerButton.x - rowButton.x)).toBeLessThanOrEqual(1)
  await page.screenshot({ path: '/private/tmp/horizon-cost-header.png', animations: 'disabled' })
  const oldPrice = await price.inputValue()
  await refreshLine.click()
  const dialog = page.getByRole('dialog', { name: 'Actualiser les coûts', exact: true })
  await expect(dialog).toContainText('Aucun coût différent disponible')
  await expect(dialog.getByRole('region', { name: 'Impact sur le devis', exact: true })).toContainText('Aucune ligne sélectionnée')
  await expect(dialog.getByRole('columnheader', { name: 'Coût actuel', exact: true })).toBeVisible()
  await expect(dialog).toContainText('Coût de référence produit')
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  await changeCost(120)
  await page.getByRole('button', { name: 'Actualiser les coûts', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: 'Actualiser la ligne 1', exact: true })).toBeChecked()
  await expect(dialog.getByRole('checkbox', { name: 'Actualiser la ligne 2', exact: true })).not.toBeChecked()
  await expect(dialog.getByRole('radio', { name: 'Conserver les prix de vente', exact: true })).toBeChecked()
  await expect(dialog).not.toContainText('Coût personnalisé ou historique : sélection manuelle.')
  const firstComparison = dialog.locator('tbody tr').first()
  await expect(firstComparison.locator('td').nth(2)).toContainText('Coût de référence produit')
  expect((await firstComparison.boundingBox())!.height).toBeLessThanOrEqual(42)
  await expect(dialog.getByRole('region', { name: 'Impact sur le devis', exact: true })).toContainText('1 ligne sélectionnée')
  await page.screenshot({ path: '/private/tmp/horizon-cost-refresh-light.png', animations: 'disabled' })
  await dialog.getByRole('radio', { name: 'Conserver les taux de marge', exact: true }).check()
  await expect(dialog.locator('.quote-cost-form')).toHaveAttribute('aria-busy', 'false')
  await dialog.getByRole('radio', { name: 'Conserver les prix de vente', exact: true }).check()
  await expect(dialog.getByRole('button', { name: 'Appliquer à 1 ligne', exact: true })).toBeEnabled()
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  expect((await get('horizon/sales/quotes/' + quote.id)).lines[0].unit_cost).toBe(100)
  await cost.hover()
  await page.getByRole('button', { name: 'Actualiser le coût ligne 1', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: 'Actualiser la ligne 2', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Appliquer à 1 ligne', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(await price.inputValue()).toBe(oldPrice)
  expect((await get('horizon/sales/quotes/' + quote.id)).lines[0].unit_cost).toBe(100)
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  let saved = await get('horizon/sales/quotes/' + quote.id)
  expect(saved.lines[0].unit_cost).toBe(120); expect(saved.lines[1].unit_cost).toBe(105)
  expect(saved.lines[0].catalog_snapshot.cost_origin).toBe('catalog')
  await changeCost(130)
  await page.getByRole('button', { name: 'Actualiser les coûts', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Appliquer à 1 ligne', exact: true })).toBeEnabled()
  await changeCost(140)
  await dialog.getByRole('button', { name: 'Appliquer à 1 ligne', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('tarifs ont changé')
  await dialog.getByRole('button', { name: 'Vérifier à nouveau', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveCount(0)
  await dialog.getByRole('checkbox', { name: 'Actualiser la ligne 2', exact: true }).check()
  await expect(dialog.getByRole('button', { name: 'Appliquer à 2 lignes', exact: true })).toBeEnabled()
  await dialog.getByRole('button', { name: 'Appliquer à 2 lignes', exact: true }).click()
  // Undo remains the ordinary form discard action; no persistent banner.
  await page.getByRole('button', { name: 'Annuler les modifications', exact: true }).click()
  saved = await get('horizon/sales/quotes/' + quote.id); expect(saved.lines[0].unit_cost).toBe(120)
  const darkToggle = page.getByRole('button', { name: 'Passer en mode sombre', exact: true }); if (await darkToggle.isVisible()) await darkToggle.click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Actualiser les coûts', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Appliquer à 1 ligne', exact: true })).toBeEnabled()
  await page.screenshot({ path: '/private/tmp/horizon-cost-refresh-dark.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  const mobileTable = (await dialog.locator('[data-table-viewport]').boundingBox())!
  expect(mobileTable.height).toBeGreaterThan(70)
  const mobileDialog = (await dialog.boundingBox())!
  expect(mobileDialog.x).toBeGreaterThanOrEqual(0); expect(mobileDialog.x + mobileDialog.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '/private/tmp/horizon-cost-refresh-mobile.png', animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  await page.getByRole('button', { name: 'Passer en mode clair', exact: true }).click()
})
