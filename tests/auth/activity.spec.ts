import { test, expect } from '@playwright/test'

test('Activité : filtres cumulés, pagination, vues, fiche en popup et présentation commune', async ({ page, request }) => {
  test.setTimeout(60_000)
  const api = 'http://127.0.0.1:18090/api'
  const authResponse = await request.post(`${api}/collections/core_users/auth-with-password`, { data: { identity: 'writer@local.invalid', password: 'Local-Horizon-test-only-2026!' } })
  expect(authResponse.ok()).toBe(true)
  const auth = await authResponse.json(), headers = { Authorization: auth.token }, marker = 'Activité navigateur'
  const companyResponse = await request.post(`${api}/collections/contacts_companies/records`, { headers, data: { name: marker, active: true } })
  expect(companyResponse.ok()).toBe(true)
  const company = await companyResponse.json()
  for (let n = 0; n < 23; n++) {
    const response = await request.post(`${api}/collections/core_activity_events/records`, { headers, data: { source_module: 'contacts', source_entity: 'contacts_companies', source_record_id: company.id, body: `Échange ${n}`, type: 'note', mentions: [] } })
    expect(response.ok()).toBe(true)
  }
  await page.goto('/login'); await page.getByLabel('Adresse e-mail', { exact: true }).fill('writer@local.invalid'); await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!'); await page.getByRole('button', { name: 'Se connecter', exact: true }).click(); await expect(page).not.toHaveURL(/\/login/)
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/'); await page.getByRole('link', { name: 'Voir toute mon activité', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Activité', exact: true })).toBeVisible(); await expect(page).toHaveURL(/view=own/); await page.getByRole('tab', { name: 'Équipe', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Rechercher dans l’activité', exact: true }).fill(marker)
  await page.getByRole('button', { name: /^Filtres de recherche/ }).click()
  const filters = page.getByRole('dialog', { name: 'Filtres de recherche', exact: true })
  await filters.getByRole('checkbox', { name: 'Contacts', exact: true }).locator('..').click()
  await filters.getByRole('checkbox', { name: 'Commentaires', exact: true }).locator('..').click()
  await filters.getByRole('checkbox', { name: 'Tâches', exact: true }).locator('..').click()
  await filters.getByRole('button', { name: 'Terminé', exact: true }).click()
  const timeline = page.getByRole('list', { name: 'Événements d’activité', exact: true })
  await expect(timeline.locator(':scope > li')).toHaveCount(20)
  await expect(page.getByText('Page 1 / 2', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Page suivante', exact: true }).click()
  await expect(timeline.locator(':scope > li')).toHaveCount(3)
  await expect(page).toHaveURL(/page=2/)
  await page.reload(); await expect(page.getByText('Page 2 / 2', { exact: true })).toBeVisible()
  const before = page.url()
  await timeline.getByRole('link', { name: marker, exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: 'Fiche société', exact: true })
  await expect(dialog).toBeVisible(); await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0); expect(page.url()).toBe(before)
  await page.getByRole('button', { name: /^Filtres de recherche/ }).click()
  await filters.getByRole('radio', { name: 'Module', exact: true }).locator('..').click()
  await filters.getByRole('button', { name: 'Terminé', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Contacts : 23 événements', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Mes mentions', exact: true }).click()
  await expect(page.getByText('Aucune activité pour cette sélection', { exact: true })).toBeVisible(); await expect(page).not.toHaveURL(/page=/)
  await page.getByRole('tab', { name: 'Mon activité', exact: true }).click(); await expect(timeline.locator(':scope > li')).toHaveCount(20)
  await page.getByRole('button', { name: 'Réinitialiser tous les filtres', exact: true }).click()
  await expect(page.getByRole('searchbox', { name: 'Rechercher dans l’activité', exact: true })).toHaveValue(marker)
  await expect(page).not.toHaveURL(/type=|module=/)
  await expect(page.getByRole('group', { name: 'Filtres appliqués', exact: true })).toHaveCount(0)
  await expect(timeline.locator(':scope > li')).toHaveCount(20)
  await page.screenshot({ path: '/private/tmp/horizon-activity-light.png' })
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-activity-dark.png' })
  await page.goto('/contacts?view=list'); await expect(page.getByRole('heading', { name: 'Contacts', exact: true })).toBeVisible(); await page.screenshot({ path: '/private/tmp/horizon-activity-reference-contacts.png' })
  await page.goto('/activity?q=' + encodeURIComponent(marker)); await page.setViewportSize({ width: 390, height: 844 })
  await expect(timeline.locator(':scope > li')).toHaveCount(20)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-activity-mobile.png' })
  const taskResponse = await request.post(`${api}/collections/core_activity_events/records`, { headers, data: { source_module: 'contacts', source_entity: 'contacts_companies', source_record_id: company.id, body: 'Action navigateur dédiée', type: 'task', mentions: [], metadata: { task: { title: 'Action navigateur dédiée', assigned_to: auth.record.id, due_date: '', priority: 'normal' } } } })
  expect(taskResponse.ok()).toBe(true)
  const task = await taskResponse.json()
  const tasksResponse = await request.get(`${api}/horizon/activity/tasks?entity=contacts_companies&id=${company.id}`, { headers })
  expect(tasksResponse.ok()).toBe(true)
  const tasks = await tasksResponse.json(), createdTask = tasks.items.find((item: { activity_event: string }) => item.activity_event === task.id)
  expect(createdTask).toBeTruthy()
  const update = await request.patch(`${api}/collections/core_tasks/records/${createdTask.id}`, { headers, data: { status: 'done' } })
  expect(update.ok()).toBe(true)
  await page.goto('/activity?type=tasks&q=' + encodeURIComponent('Action navigateur dédiée'))
  await expect(page.getByText('a créé une tâche', { exact: true })).toHaveCount(1)
  await expect(page.getByText('a mis à jour une tâche', { exact: true })).toHaveCount(1)

})
