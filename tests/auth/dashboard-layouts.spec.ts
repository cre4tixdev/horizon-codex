import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  await expect(page.getByRole('button', { name: 'Modifier', exact: true })).toBeEnabled()
}

test('Dashboards personnels : édition, grille, sauvegarde, défaut et autre navigateur', async ({ page, browser }) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1600, height: 1100 })
  await login(page)
  const grid = page.locator('.dashboard-widget-grid')
  await expect(grid.locator('.dashboard-widget')).toHaveCount(8)
  await expect(page.getByRole('region', { name: 'Chiffre d’affaires prévu', exact: true }).locator('.kpi__value')).toHaveText('0')
  await page.getByRole('button', { name: 'Modifier', exact: true }).click()
  await page.getByLabel('Nom du dashboard', { exact: true }).fill('Mon pilotage')
  await page.getByRole('button', { name: 'Retirer Facturé', exact: true }).click()
  await expect(grid.locator('.dashboard-widget')).toHaveCount(7)
  await page.getByRole('button', { name: 'Ajouter un widget', exact: true }).click()
  const catalog = page.getByRole('dialog', { name: 'Ajouter un widget', exact: true })
  await catalog.locator('.dashboard-widget-catalog > div').filter({ hasText: 'Facturé' }).getByRole('button', { name: 'Ajouter', exact: true }).click()
  await expect(grid.locator('.dashboard-widget')).toHaveCount(8)
  await page.getByRole('button', { name: 'Configurer Chiffre d’affaires prévu', exact: true }).click()
  const dimensions = page.getByRole('dialog', { name: 'Chiffre d’affaires prévu', exact: true })
  await dimensions.getByRole('combobox', { name: 'Largeur du widget', exact: true }).click()
  await page.getByRole('option', { name: '6 / 12 colonnes', exact: true }).click()
  await dimensions.getByLabel('Hauteur du widget', { exact: true }).fill('3')
  await dimensions.getByRole('button', { name: 'Terminer', exact: true }).click()
  const resize = page.getByRole('button', { name: 'Redimensionner Chiffre d’affaires prévu', exact: true })
  await resize.focus(); await resize.press('ArrowRight'); await resize.press('ArrowDown')
  await expect(grid.locator('[data-kind=forecast]')).toHaveCSS('grid-column-end', 'span 8')
  await expect(grid.locator('[data-kind=forecast]')).toHaveCSS('grid-row-end', 'span 4')
  // Real pointer reordering through the dedicated handle.
  const before = await grid.locator('.dashboard-widget').evaluateAll((elements) => elements.map((element) => element.getAttribute('data-kind')))
  const from = (await page.getByRole('button', { name: 'Déplacer Commandé', exact: true }).boundingBox())!
  const to = (await grid.locator('[data-kind=margin]').boundingBox())!
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 20 })
  await page.mouse.up()
  await expect.poll(async () => grid.locator('.dashboard-widget').evaluateAll((elements) => elements.map((element) => element.getAttribute('data-kind')))).not.toEqual(before)
  // All rectangles fit the grid and never overlap after moving / resizing.
  const tiles = await grid.locator('.dashboard-widget').evaluateAll((elements) => elements.map((element) => { const r = element.getBoundingClientRect(); return { x: r.x, y: r.y, right: r.right, bottom: r.bottom } }))
  for (let i = 0; i < tiles.length; i++) for (let j = i + 1; j < tiles.length; j++) expect(tiles[i]!.right <= tiles[j]!.x || tiles[j]!.right <= tiles[i]!.x || tiles[i]!.bottom <= tiles[j]!.y || tiles[j]!.bottom <= tiles[i]!.y).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-widgets-edit.png', fullPage: true, animations: 'disabled' })
  // Conflict keeps the draft intact; a retry saves the original revision.
  await page.route('**/api/horizon/dashboard/layouts', async (route) => {
    if (route.request().method() === 'POST') { await route.fulfill({ status: 409, json: { status: 409, message: 'Conflict', data: {} } }); await page.unroute('**/api/horizon/dashboard/layouts') }
    else await route.continue()
  })
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('modifiés ailleurs')
  await expect(page.getByLabel('Nom du dashboard')).toHaveValue('Mon pilotage')
  const saved = page.waitForResponse((response) => response.url().endsWith('/dashboard/layouts') && response.request().method() === 'POST' && response.status() === 200)
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  const body = await (await saved).json()
  expect(body.preference.dashboards[0].widgets.find((widget: { type: string }) => widget.type === 'forecast')).toEqual({ type: 'forecast', width: 8, height: 4 })
  await expect(page.getByLabel('Nom du dashboard')).toHaveCount(0)
  await page.getByRole('button', { name: 'Définir comme dashboard par défaut', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Définir comme dashboard par défaut', exact: true })).toBeDisabled()
  const other = await browser.newContext({ baseURL: 'http://127.0.0.1:4174', viewport: { width: 1600, height: 1000 } })
  const second = await other.newPage()
  await login(second)
  await expect(second.getByRole('combobox', { name: 'Dashboard à afficher', exact: true })).toContainText('Mon pilotage · par défaut')
  await expect(second.locator('[data-kind=forecast]')).toHaveCSS('grid-column-end', 'span 8')
  await other.close()
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Dashboard à afficher', exact: true })).toContainText('Mon pilotage')
  // Pointer resize, then cancellation restores the saved width.
  await page.getByRole('button', { name: 'Modifier', exact: true }).click()
  const corner = (await resize.boundingBox())!
  await page.mouse.move(corner.x + 10, corner.y + 10); await page.mouse.down()
  await page.mouse.move(corner.x + 450, corner.y + 104, { steps: 12 }); await page.mouse.up()
  await expect(grid.locator('[data-kind=forecast]')).toHaveCSS('grid-column-end', 'span 12')
  await page.getByRole('button', { name: 'Annuler', exact: true }).click()
  await page.getByRole('dialog', { name: 'Annuler les modifications ?', exact: true }).getByRole('button', { name: 'Abandonner les modifications', exact: true }).click()
  await expect(grid.locator('[data-kind=forecast]')).toHaveCSS('grid-column-end', 'span 8')
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-widgets-dark.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-widgets-mobile.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Passer en mode clair', exact: true }).click()
  // Clean up via the actual UI, fallback to the immutable Horizon template.
  await page.getByRole('button', { name: 'Supprimer ce dashboard', exact: true }).click()
  await page.getByRole('dialog', { name: 'Supprimer ce dashboard ?', exact: true }).getByRole('button', { name: 'Supprimer', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Dashboard à afficher', exact: true })).toHaveText('Horizon · par défaut')
  expect(errors).toEqual([])
})

test('Dashboards : déplacement clavier, plusieurs copies et suppression indépendante', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await login(page)
  await page.getByRole('button', { name: 'Dupliquer', exact: true }).click()
  await page.getByLabel('Nom du dashboard').fill('Vue personnelle A')
  const grid = page.locator('.dashboard-widget-grid')
  const before = await grid.locator('.dashboard-widget').evaluateAll((items) => items.map((item) => item.getAttribute('data-kind')))
  const handle = page.getByRole('button', { name: 'Déplacer Commandé', exact: true })
  await handle.focus(); await handle.press('Space'); await handle.press('ArrowRight'); await handle.press('Space')
  await expect.poll(() => grid.locator('.dashboard-widget').evaluateAll((items) => items.map((item) => item.getAttribute('data-kind')))).not.toEqual(before)
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  const selector = page.getByRole('combobox', { name: 'Dashboard à afficher', exact: true })
  await expect(selector).toHaveText('Vue personnelle A')
  await page.getByRole('button', { name: 'Dupliquer', exact: true }).click()
  await page.getByLabel('Nom du dashboard').fill('Vue personnelle B')
  await page.getByRole('button', { name: 'Retirer Chiffre d’affaires prévu', exact: true }).click()
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(selector).toHaveText('Vue personnelle B')
  await selector.click()
  await expect(page.getByRole('option')).toHaveCount(3)
  await page.getByRole('option', { name: 'Vue personnelle A', exact: true }).click()
  await expect(grid.locator('[data-kind=forecast]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Supprimer ce dashboard', exact: true }).click()
  await page.getByRole('dialog', { name: 'Supprimer ce dashboard ?', exact: true }).getByRole('button', { name: 'Supprimer', exact: true }).click()
  await expect(selector).toContainText('Horizon')
  await selector.click(); await page.getByRole('option', { name: 'Vue personnelle B', exact: true }).click()
  await expect(grid.locator('[data-kind=forecast]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Supprimer ce dashboard', exact: true }).click()
  await page.getByRole('dialog', { name: 'Supprimer ce dashboard ?', exact: true }).getByRole('button', { name: 'Supprimer', exact: true }).click()
  await expect(selector).toHaveText('Horizon · par défaut')
})
