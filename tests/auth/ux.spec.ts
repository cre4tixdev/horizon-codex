test('UX : une modification concurrente conserve le brouillon local et refuse de l’écraser', async ({ page, browser }) => {
  await login(page)
  await page.goto('/settings/ux?tab=tables')
  await page.getByLabel('Hauteur des lignes', { exact: true }).fill('38')
  const context = await browser.newContext({ baseURL: 'http://127.0.0.1:4174' })
  try {
    const other = await context.newPage()
    await login(other)
    await other.goto('/settings/ux?tab=tables')
    await other.getByLabel('Hauteur des lignes', { exact: true }).fill('34')
    await other.getByRole('button', { name: 'Enregistrer', exact: true }).click()
    await expect(page.getByText(/Les réglages ont été modifiés ailleurs/)).toBeVisible()
    await expect(page.getByLabel('Hauteur des lignes', { exact: true })).toHaveValue('38')
    await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
    await expect(page.getByText('Les réglages UX ont changé. Rechargez-les avant d’enregistrer.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Recharger', exact: true }).click()
    await expect(page.getByLabel('Hauteur des lignes', { exact: true })).toHaveValue('34')
    await page.getByRole('button', { name: 'Valeurs par défaut Horizon', exact: true }).click()
    await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
    await expect(page.locator('html')).toHaveCSS('--hz-table-row-height', '32px')
  } finally { await context.close() }
})

