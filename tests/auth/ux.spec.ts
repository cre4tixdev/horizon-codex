import { expect, test, type Page } from '@playwright/test'
async function login(page: Page, email = 'erp-admin@local.invalid') {
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill(email)
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
}
async function expandSections(page: Page) {
  await expect(page.getByRole('button', { name: /^Tout (déplier|replier)$/ })).toBeVisible()
  const expand = page.getByRole('button', { name: 'Tout déplier', exact: true })
  if (await expand.isVisible()) await expand.click()
  await expect(page.locator('.ux-controls details:not([open])')).toHaveCount(0)
}
