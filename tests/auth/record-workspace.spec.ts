import { test, expect, type Page, type Locator } from '@playwright/test'
async function expectWorkspaceCentered(page: Page, dialog: Locator) {
  const workspace = (await page.locator('.app-workspace').boundingBox())!
  const popup = (await dialog.boundingBox())!
  expect(popup.x).toBeGreaterThan(workspace.x)
  expect(popup.x + popup.width).toBeLessThan(workspace.x + workspace.width)
  expect(Math.abs(popup.x + popup.width / 2 - workspace.x - workspace.width / 2)).toBeLessThan(1)
}
async function login(page: Page, email = 'crm@local.invalid') {
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill(email)
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
}
