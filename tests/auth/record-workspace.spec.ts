test('popups imbriqués et consultation en lecture seule', async ({ page }) => {
  await login(page)
  await page.goto('/contacts/companies/new')
  await page.getByLabel('Nom usuel', { exact: true }).fill('Client Nested Readonly')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/\/contacts\/companies\/(?!new)/)
  await expect(page.locator('.page-breadcrumb-record-actions').getByRole('button', { name: 'Enregistrer', exact: true })).toBeVisible()
  await expect(page.locator('.page-breadcrumb-record-actions').getByRole('button', { name: 'Actions de la fiche', exact: true })).toBeVisible()
  await page.screenshot({ path: '/private/tmp/horizon-contact-top-actions.png' })
  const companyId = new URL(page.url()).pathname.split('/').at(-1)!
  await page.goto(`/contacts/people/new?company=${companyId}`)
  await page.getByRole('button', { name: 'Réduire la navigation', exact: true }).click()
  await page.getByLabel('Nom', { exact: true }).fill('Brouillon extérieur')
  let release: (() => void) | undefined
  const gate = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/api/collections/contacts_addresses/records*', async (route) => { await gate; await route.continue() })
  await page.getByRole('button', { name: 'Ouvrir la fiche : Société', exact: true }).click()
  const company = page.getByRole('dialog', { name: 'Fiche société', exact: true })
  const loading = company.getByRole('status', { name: 'Chargement de la fiche…' })
  await expect(loading).toHaveText('')
  await expect(company.getByText('Chargement de la fiche…', { exact: true })).toHaveCount(0)
  const ring = loading.locator('.h-loading-ring')
  expect(await ring.evaluate((element) => element.getAnimations().some((animation) => animation.effect?.getTiming().delay === 200))).toBe(true)
  await expect(ring).toHaveCSS('opacity', '1')
  await page.screenshot({ path: '/private/tmp/horizon-record-popup-loading.png' })
  release?.()
  await expect(loading).toHaveCount(0)
  await page.unroute('**/api/collections/contacts_addresses/records*')
  await expectWorkspaceCentered(page, company)
  await page.screenshot({ path: '/private/tmp/horizon-record-popup-collapsed.png' })
  await company.getByRole('tab', { name: /^Contacts(?: \d+)?$/ }).click()
  await company.getByRole('link', { name: 'Ajouter un contact', exact: true }).click()
  const person = page.getByRole('dialog', { name: 'Créer un contact', exact: true })
  await person.getByLabel('Nom', { exact: true }).fill('Contact créé imbriqué')
  await person.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(person).not.toBeVisible()
  await expect(company.getByRole('link', { name: 'Contact créé imbriqué', exact: true })).toBeVisible()
  await company.getByRole('button', { name: 'Fermer', exact: true }).click()
  await expect(page.getByLabel('Nom', { exact: true })).toHaveValue('Brouillon extérieur')
  await expect(page).toHaveURL(`/contacts/people/new?company=${companyId}`)
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/\/contacts\/people\/(?!new)/)
  const contactUrl = page.url()
  await page.getByRole('button', { name: 'Menu utilisateur', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Se déconnecter', exact: true }).click()
  await login(page, 'crm-reader@local.invalid')
  await page.goto(contactUrl)
  await page.getByRole('button', { name: 'Ouvrir la fiche : Société', exact: true }).click()
  await expect(company.getByLabel('Nom usuel', { exact: true })).toBeDisabled()
  await expect(company.getByRole('button', { name: 'Enregistrer', exact: true })).toHaveCount(0)
  await page.screenshot({ path: '/private/tmp/horizon-record-popup-readonly.png' })
  await company.getByRole('button', { name: 'Fermer', exact: true }).click()
  const inspect = page.getByRole('button', { name: 'Ouvrir la fiche : Société', exact: true })
  await expect(inspect).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(inspect).toBeFocused()
  await expect(inspect).toHaveCSS('outline-style', 'none')
  const focusedGroup = page.locator('.h-combobox-with-actions').filter({ has: inspect })
  expect(await focusedGroup.evaluate((element) => element.matches(':has(:focus-visible)'))).toBe(true)
  await expect(focusedGroup).toHaveCSS('border-color', 'rgb(113, 137, 171)')
  await page.screenshot({ path: '/private/tmp/horizon-record-picker-focus.png' })
})

test('sauvegarde de fiche : onglet conservé à la création et après modification', async ({ page }) => {
  await login(page)
  await page.goto('/contacts/companies/new')
  await page.getByLabel('Nom usuel', { exact: true }).fill('Client onglet conservé')
  const notes = page.getByRole('tab', { name: 'Notes', exact: true })
  await notes.click()
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Première note')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/contacts\/companies\/(?!new)/)
  await expect(notes).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Première note')
  const companyId = new URL(page.url()).pathname.split('/').at(-1)!
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Note modifiée')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  await expect(notes).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Note modifiée')
  await page.goto(`/crm/opportunities/new?company=${companyId}`)
  await page.getByLabel('Titre', { exact: true }).fill('Affaire onglet conservé')
  const descriptionTab = page.getByRole('tab', { name: 'Description', exact: true })
  await descriptionTab.click()
  const description = page.getByRole('textbox', { name: 'Contexte et besoins', exact: true })
  await description.fill('Première description')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/crm\/opportunities\/(?!new)/)
  await expect(descriptionTab).toHaveAttribute('aria-selected', 'true')
  await description.fill('Description modifiée')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  await expect(descriptionTab).toHaveAttribute('aria-selected', 'true')
  await expect(description).toHaveText('Description modifiée')
})
