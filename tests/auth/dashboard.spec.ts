import { expect, test } from '@playwright/test'

test('Dashboard : carrousel automatique, pause mémorisée, navigation et données métier', async ({ page }) => {
  test.setTimeout(60_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.clock.install()
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const periods = page.getByRole('group', { name: 'Période des indicateurs et du pilotage', exact: true })
  await expect(periods.getByRole('button', { name: 'Mois', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const personalActivity = page.getByRole('region', { name: 'Mon activité récente', exact: true })
  await expect(personalActivity.getByRole('heading', { name: 'Mon activité récente', exact: true })).toBeVisible()
  await expect(personalActivity.getByText('Équipe', { exact: true })).toHaveCount(0)
  await expect(personalActivity.getByRole('link', { name: 'Voir toute mon activité', exact: true })).toHaveAttribute('href', '/activity?view=own')
  const initialCaption = await page.locator('.dashboard-period-navigation > span').innerText()
  const heights = await page.locator('.dashboard-date, .dashboard-period-controls').evaluateAll((elements) => elements.map((element) => element.getBoundingClientRect().height))
  expect(heights[0]).toBe(heights[1])
  await expect(page.locator('.dashboard-period-controls')).toHaveCSS('border-top-style', 'solid')
  await expect(page.locator('.dashboard-period-controls')).toHaveCSS('border-top-width', '1px')
  await periods.getByRole('button', { name: 'Trimestre', exact: true }).click()
  await expect(periods.getByRole('button', { name: 'Trimestre', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const currentCaption = await page.locator('.dashboard-period-navigation > span').innerText()
  await page.getByRole('button', { name: 'Période précédente', exact: true }).click()
  await expect(page.locator('.dashboard-period-navigation > span')).not.toHaveText(currentCaption)
  await periods.getByRole('button', { name: 'Année', exact: true }).click()
  await expect(page.locator('.dashboard-period-navigation > span')).toHaveAttribute('title', /1 janvier/)
  await expect(page.locator('.dashboard-period-navigation > span')).toHaveAttribute('title', /31 décembre/)
  await page.reload()
  await expect(periods.getByRole('button', { name: 'Mois', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.dashboard-period-navigation > span')).toHaveText(initialCaption)
  await expect(page.getByRole('heading', { name: 'Aucune échéance cette semaine', exact: true })).toBeVisible()
  const planningHeading = page.getByRole('region', { name: 'Mon planning', exact: true }).locator('.panel-heading')
  await expect(planningHeading).toContainText('Vos tâches et échéances · 7 prochains jours')
  const headingBounds = (await planningHeading.getByRole('heading').boundingBox())!
  const subtitleBounds = (await planningHeading.locator('.dashboard-feed-subtitle').boundingBox())!
  expect(Math.abs(headingBounds.y + headingBounds.height / 2 - subtitleBounds.y - subtitleBounds.height / 2)).toBeLessThan(2)
  const carousel = page.getByRole('region', { name: 'Suivi commercial', exact: true })
  await expect(carousel.getByRole('heading', { name: 'Opportunités', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Accès rapides', exact: true })).toHaveCount(0)
  await page.mouse.move(1, 1)
  await page.clock.fastForward(10_100)
  await expect(carousel.getByRole('heading', { name: 'Devis', exact: true })).toBeVisible()
  await expect(carousel.getByRole('link', { name: 'Tout voir : Devis', exact: true })).toHaveAttribute('href', '/sales/quotes?kind=quote')
  await carousel.getByRole('button', { name: 'Mettre en pause', exact: true }).click()
  await page.getByRole('navigation', { name: 'Navigation principale', exact: true }).getByRole('link', { name: 'Dashboard', exact: true }).focus()
  await page.mouse.move(1, 1)
  await page.clock.fastForward(30_000)
  await expect(carousel.getByRole('heading', { name: 'Devis', exact: true })).toBeVisible()
  await carousel.getByRole('button', { name: 'Afficher Commandes clients', exact: true }).click()
  await expect(carousel.getByRole('link', { name: 'Tout voir : Commandes clients', exact: true })).toHaveAttribute('href', '/sales/quotes?kind=order')
  await carousel.getByRole('button', { name: 'Page suivante du carrousel', exact: true }).click()
  await expect(carousel.getByRole('heading', { name: 'Factures', exact: true })).toBeVisible()
  await page.reload()
  await expect(carousel.getByRole('button', { name: 'Reprendre le défilement', exact: true })).toBeVisible()
  await page.mouse.move(1, 1)
  await page.clock.fastForward(30_000)
  await expect(carousel.getByRole('heading', { name: 'Opportunités', exact: true })).toBeVisible()
  await carousel.getByRole('button', { name: 'Reprendre le défilement', exact: true }).click()
  await page.clock.runFor(300)
  await page.getByRole('navigation', { name: 'Navigation principale', exact: true }).getByRole('link', { name: 'Dashboard', exact: true }).focus()
  await page.mouse.move(1, 1)
  await page.clock.fastForward(10_100)
  await expect(carousel.getByRole('heading', { name: 'Devis', exact: true })).toBeVisible()
  await carousel.getByRole('button', { name: 'Mettre en pause', exact: true }).click()
  const content = carousel.locator('.dashboard-carousel-content')
  const bounds = (await content.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width * .7, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .3, bounds.y + bounds.height / 2, { steps: 10 })
  await page.mouse.up()
  await expect(carousel.getByRole('heading', { name: 'Commandes clients', exact: true })).toBeVisible()
  await page.goto('/contacts/companies/new')
  await page.getByLabel('Nom usuel', { exact: true }).fill('Client carrousel')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/contacts\/companies\/(?!new)/)
  await page.goto('/crm/opportunities/new')
  await page.getByLabel('Titre', { exact: true }).fill('Affaire carrousel')
  await page.getByLabel('Montant estimé', { exact: true }).fill('1500')
  const today = await page.evaluate(() => new Intl.DateTimeFormat('fr-CA', { timeZone: 'Europe/Paris', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date()))
  await page.getByLabel('Échéance prévue', { exact: true }).fill(today)
  await page.getByRole('combobox', { name: 'Société', exact: true }).click()
  await page.getByRole('option', { name: 'Client carrousel', exact: true }).click()
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/crm\/opportunities\/(?!new)/)
  const opportunityPath = new URL(page.url()).pathname
  await page.getByRole('button', { name: 'Tâche', exact: true }).click()
  await page.getByLabel('Message du fil', { exact: true }).fill('Préparer la réunion client')
  await page.getByLabel('Titre de la tâche', { exact: true }).fill('Appeler le client carrousel')
  await page.getByLabel('Échéance de la tâche', { exact: true }).fill(today)
  await page.getByRole('button', { name: 'Créer la tâche', exact: true }).click()
  await expect(page.getByLabel('Message du fil', { exact: true })).toHaveValue('')
  await page.goto('/')
  await expect(carousel).toContainText('Affaire carrousel')
  const forecast = page.getByRole('region', { name: 'Chiffre d’affaires prévu', exact: true })
  await expect(forecast.locator('.kpi__value')).toHaveText(/1\s?500,00/ )
  await expect(page.locator('.dashboard-feed--activity')).toContainText('Affaire carrousel')
  await expect(page.getByRole('region', { name: 'Mon planning', exact: true }).locator('.dashboard-feed')).toContainText('Appeler le client carrousel')
  await page.getByRole('button', { name: 'Période précédente', exact: true }).click()
  await expect(forecast.locator('.kpi__value')).toHaveText('0')
  await page.getByRole('button', { name: 'Période suivante', exact: true }).click()
  await expect(forecast.locator('.kpi__value')).toHaveText(/1\s?500,00/)
  await expect(carousel).toContainText('Client carrousel')
  await carousel.locator('tbody').getByRole('link').first().click()
  await expect(page).toHaveURL(new RegExp(opportunityPath))
  await page.getByRole('link', { name: 'Nouveau devis', exact: true }).click()
  await page.getByLabel('Titre du devis', { exact: true }).fill('Proposition carrousel')
  await page.getByRole('button', { name: 'Ajouter une ligne', exact: true }).click()
  await page.getByLabel('Description ligne 1', { exact: true }).fill('Installation')
  await page.getByLabel('Coût ligne 1', { exact: true }).fill('60')
  await page.getByLabel('Prix unitaire ligne 1', { exact: true }).fill('100')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/sales\/quotes\/(?!new)/)
  const quotePath = new URL(page.url()).pathname
  await page.goto('/')
  await carousel.getByRole('button', { name: 'Afficher Devis', exact: true }).click()
  await expect(carousel).toContainText('Proposition carrousel')
  await carousel.getByRole('button', { name: 'Afficher Commandes clients', exact: true }).click()
  await expect(carousel).not.toContainText('Proposition carrousel')
  await carousel.getByRole('button', { name: 'Afficher Devis', exact: true }).click()
  await page.goto(quotePath)
  await page.getByRole('button', { name: 'Finaliser Devis', exact: true }).click()
  await page.getByRole('dialog', { name: 'Finaliser le devis' }).getByRole('button', { name: 'Confirmer', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmer', exact: true }).click()
  await page.getByRole('dialog', { name: 'Confirmer la commande client' }).getByRole('checkbox', { name: 'Attente Commande', exact: true }).check()
  await page.getByRole('dialog', { name: 'Confirmer la commande client' }).getByRole('button', { name: 'Confirmer la commande', exact: true }).click()
  await expect(page.locator('.quote-progress [aria-current=step]')).toContainText('Commande client')
  await page.goto('/')
  await expect(page.getByRole('region', { name: 'Commandé', exact: true }).locator('.kpi__value')).toHaveText(/100,00/)
  await expect(page.getByRole('region', { name: 'Marge prévisionnelle', exact: true }).locator('.kpi__value')).toHaveText(/40,00.*40/ )
  await expect(page.locator('.dashboard-widget-grid')).toHaveCSS('grid-template-columns', /(?:[\d.]+px ){11}[\d.]+px/)
  await page.locator('.dashboard-widget[data-kind=economic]').scrollIntoViewIfNeeded()
  await expect(page.locator('.economic-flow')).toContainText('Prévu')
  await expect(page.locator('.economic-flow')).toContainText('Engagé')
  await expect(page.locator('.economic-flow')).toContainText('Réalisé')
  await expect(page.locator('.economic-flow')).toContainText('Facturé')
  await expect(page.locator('.economic-flow')).toContainText('Payé')
  const orderTile = page.getByRole('region', { name: 'Commandé', exact: true })
  await expect(orderTile.locator('.dashboard-kpi-trend')).toHaveAttribute('data-step', 'day')
  await expect(orderTile.locator('.dashboard-kpi-trend svg')).toHaveAttribute('data-currency', 'EUR')
  await expect(page.getByRole('region', { name: 'Facturé', exact: true }).locator('.dashboard-kpi-trend')).toHaveCount(0)
  await periods.getByRole('button', { name: 'Trimestre', exact: true }).click()
  await expect(orderTile.locator('.dashboard-kpi-trend')).toHaveAttribute('data-step', 'week')
  await periods.getByRole('button', { name: 'Année', exact: true }).click()
  await expect(orderTile.locator('.dashboard-kpi-trend')).toHaveAttribute('data-step', 'month')
  await periods.getByRole('button', { name: 'Mois', exact: true }).click()
  await expect(orderTile.locator('.dashboard-kpi-trend')).toHaveAttribute('data-step', 'day')
  // Les couleurs du planning suivent le référentiel partagé, pas une palette locale.
  await page.route('**/api/collections/crm_appointment_kinds/records?*', async (route) => {
    const response = await route.fetch()
    const body = await response.json()
    body.items = body.items.map((item: { code: string }) => ({ ...item, color: item.code === 'visit' ? '#2563EB' : '#7B3FC7' }))
    await route.fulfill({ response, json: body })
  })
  await page.route('**/api/horizon/calendar/events?*', async (route) => {
    const response = await route.fetch()
    const body = await response.json()
    const start = new URL(route.request().url()).searchParams.get('from')!
    body.items.push(...['visit', 'hearing'].map((kind) => ({ id: `dashboard-${kind}`, source_module: 'crm', source_entity: 'crm_opportunities', source_record_id: opportunityPath.split('/').at(-1), kind, title: kind === 'visit' ? 'Visite du site' : 'Soutenance projet', code: '00001', company: 'Client carrousel', start, end: '', all_day: true, timezone: 'Europe/Paris', location: '', href: opportunityPath })))
    await route.fulfill({ response, json: body })
  })
  await page.reload()
  const agenda = page.locator('.dashboard-agenda')
  await expect(agenda.locator('.h-tag', { hasText: 'Visite' })).toHaveCSS('--tag-color', '#2563EB')
  await expect(agenda.locator('.h-tag', { hasText: 'Soutenance' })).toHaveCSS('--tag-color', '#7B3FC7')
  await expect(page.locator('.dashboard-feed--activity .dashboard-activity-avatar')).toHaveCount(0)
  await expect(page.locator('.dashboard-feed--activity .dashboard-activity-icon').first()).toBeVisible()
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-dashboard-connected-dark.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Passer en mode clair', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-dashboard-carousel.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-dashboard-carousel-mobile.png', fullPage: true, animations: 'disabled' })
  expect(errors).toEqual([])
})
