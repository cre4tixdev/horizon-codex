async function movePurchaseLine(page: Page, from: number, to: number) {
  await expect(page.locator('.purchasing-lines tr[data-dragging=true]')).toHaveCount(0)
  const handle = page.getByRole('button', { name: `Déplacer ligne ${from}`, exact: true })
  await handle.scrollIntoViewIfNeeded()
  const start = (await handle.boundingBox())!, end = (await page.getByRole('button', { name: `Déplacer ligne ${to}`, exact: true }).boundingBox())!
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(start.x + start.width / 2, to > from ? end.y + end.height - 2 : end.y + 2, { steps: 15 })
  await page.mouse.up()
}
