import { test, expect } from '@playwright/test'

test('Pagination : auto selon écran, choix manuel, groupes et navigation', async ({ page, request }) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width: 1600, height: 1600 })
  await page.goto('/login'); await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid'); await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!'); await page.getByRole('button', { name: 'Se connecter', exact: true }).click(); await expect(page).toHaveURL('/')
  const token = await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '')
  for (let start = 0; start < 90; start += 15) {
    const results = await Promise.all(Array.from({ length: 15 }, (_, offset) => request.post('http://127.0.0.1:18090/api/collections/contacts_companies/records', { headers: { Authorization: token }, data: { name: `Adaptive Company ${String(start + offset).padStart(3, '0')}`, active: true } })))
    for (const result of results) expect(result.ok(), await result.text()).toBe(true)
  }
  await page.goto('/contacts?view=list&q=Adaptive')
  const table = page.locator('.h-data-table'), size = page.getByRole('combobox', { name: 'Résultats par page', exact: true })
  const automatic = async () => Number((await size.innerText()).match(/Auto · (\d+)/)?.[1] || 0)
  await expect.poll(automatic).toBeGreaterThan(25)
  await expect.poll(async () => table.locator('tbody tr').count()).toBe(await automatic())
  const tall = await automatic()
  await page.screenshot({ path: '/private/tmp/horizon-list-page-size-tall.png', fullPage: true })
  await page.setViewportSize({ width: 1600, height: 800 })
  await expect.poll(automatic).toBeLessThan(tall)
  await size.click(); await page.getByRole('option', { name: '50 / page', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(50); await expect(page).toHaveURL(/perPage=50/)
  await expect(page).toHaveURL(/q=Adaptive/)
  await page.getByRole('button', { name: 'Page suivante', exact: true }).click(); await expect(table.locator('tbody tr')).toHaveCount(40)
  await page.reload(); await expect(size).toHaveText('50 / page'); await expect(table.locator('tbody tr')).toHaveCount(50)
  await page.goto('/contacts?view=list&q=Adaptive&group=country&perPage=50')
  await expect(page.locator('.h-data-table tbody tr')).toHaveCount(50)
  await page.getByRole('button', { name: 'Page suivante', exact: true }).click(); await expect(page.locator('.h-data-table tbody tr')).toHaveCount(40)
  await page.goto('/contacts?view=cards&q=Adaptive')
  await expect(size).toContainText('Auto')
  await expect.poll(automatic).toBeLessThan(25)
  await expect.poll(async () => page.locator('.contact-card-grid > *').count()).toBe(await automatic())
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-list-page-size-cards-dark.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(size).toBeVisible()
  await expect.poll(automatic).toBeLessThanOrEqual(5)
  await expect.poll(async () => page.locator('.contact-card-grid > *').count()).toBe(await automatic())
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  const nav = (await page.getByRole('navigation', { name: 'Pagination des contacts', exact: true }).boundingBox())!, create = (await page.getByRole('link', { name: 'Nouvelle société', exact: true }).boundingBox())!
  expect(Math.min(nav.x + nav.width, create.x + create.width) > Math.max(nav.x, create.x) && Math.min(nav.y + nav.height, create.y + create.height) > Math.max(nav.y, create.y)).toBe(false)
  await page.screenshot({ path: '/private/tmp/horizon-list-page-size-mobile.png', fullPage: true })
})
