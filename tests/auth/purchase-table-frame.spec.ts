import { expect, test } from '@playwright/test'

test('Commandes fournisseurs : cadre du tableau filtré vide et rempli', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  await page.goto('/purchasing/orders?source_line=3ar64f9zjnsoqsy')
  const table = page.locator('.h-data-table')
  await expect(page.getByRole('heading', { name: 'Aucune pièce d’achat', exact: true })).toBeVisible()
  await expect(table.locator('tbody tr')).toHaveCount(0)
  await page.screenshot({ path: '/private/tmp/horizon-purchase-empty-table-light.png', fullPage: true })
  async function frame(empty: boolean) {
    await expect(table).toHaveCSS('border-radius', '6px')
    await expect(table).toHaveCSS('box-shadow', 'none')
    await expect(table.locator('..')).toHaveCSS('border-bottom-width', '0px')
    await expect(table.locator('..')).toHaveCSS('box-shadow', 'none')
    await expect(table.locator('thead th').first()).toHaveCSS('border-bottom-left-radius', empty ? '5px' : '0px')
    await expect(table.locator('thead th').last()).toHaveCSS('border-bottom-right-radius', empty ? '5px' : '0px')
    for (const header of await table.locator('thead th').all()) await expect(header).toHaveCSS('border-bottom-width', empty ? '0px' : '1px')
  }
  await frame(true)
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await frame(true)
  await page.screenshot({ path: '/private/tmp/horizon-purchase-empty-table-dark.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await frame(true)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-purchase-empty-table-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.getByRole('button', { name: 'Passer en mode clair', exact: true }).click()
  const token = await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '')
  const api = async (path: string, data: object) => {
    const response = await request.post(`http://127.0.0.1:18090/api/${path}`, { headers: { Authorization: token }, data })
    expect(response.status(), await response.text()).toBe(200)
    return response.json()
  }
  const company = await api('collections/contacts_companies/records', { name: 'Fournisseur cadre tableau', active: true })
  await api('collections/contacts_company_roles/records', { company: company.id, role: 'supplier', active: true })
  await api('horizon/purchasing/orders/save', { creation_key: crypto.randomUUID(), input: { title: 'Commande cadre tableau', opportunity: '', source_order: '', source_quote: '', supplier: company.id, document_date: '2026-10-15', needed_date: '', currency: 'EUR', exchange_rate: 1, tax_rate: 20, notes: '', lines: [{ purpose: 'stock', product: '', description: 'Matériel', reference: '', brand: '', quantity: 1, unit: 'u', unit_price: 10, discount: 0, supplier: company.id, source_line: '', request_line: '', allocations: [] }] } })
  await page.goto('/purchasing/orders')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await frame(false)
  await page.screenshot({ path: '/private/tmp/horizon-purchase-filled-table-light.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  const viewport = table.locator('..')
  await expect(viewport).toHaveAttribute('data-scroll-mode', 'contained')
  await viewport.evaluate((element) => { element.scrollLeft = element.scrollWidth })
  await expect.poll(() => viewport.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0)
  await frame(false)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-purchase-filled-table-mobile.png', fullPage: true })
})
