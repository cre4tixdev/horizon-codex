test('BL partiel sérialisé : choisir uniquement les exemplaires réellement livrés', async ({ page, request }) => {
  test.setTimeout(60000)
  const { api, product, location, customerOrder } = await fixture(page, request, 'serial'), quote = await customerOrder()
  const choices = await api('horizon/inventory/operations/choices')
  const warehouse = choices.locations.find((item: { id: string; warehouse: string }) => item.id === location).warehouse
  const receipt = await api('horizon/inventory/operations/save', { creation_key: crypto.randomUUID(), input: { kind: 'IN', warehouse, destination_warehouse: warehouse, title: 'Réception séries', opportunity: '', purchase_order: '', sales_quote: '', origin: '', destination: '', reason: 'Stock du test séries', notes: '', document_date: '2026-10-13', planned_date: '', inventory_mode: 'cycle', dropship: false, scrap: false, scope: [], lines: [{ id: 'line-serial', product: product.id, quantity: 2, from_location: '', to_location: location, source_line: '', counted: null, traces: [{ number: 'BL-UI-S1', quantity: 1 }, { number: 'BL-UI-S2', quantity: 1 }] }] } })
  await api('horizon/inventory/operations/transition', { id: receipt.id, updated: receipt.updated, action: 'validate' })
  await page.goto(`/sales/quotes/${quote.id}`)
  await page.getByRole('button', { name: 'Préparer la livraison', exact: true }).click()
  await expect(page).toHaveURL(/inventory\/operations\/[a-z0-9]{15}$/)
  await page.getByRole('button', { name: 'Valider', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Confirmer la réalisation', exact: true })
  await expect(confirmation.getByLabel('Quantité à livrer · Produit à livrer', { exact: true })).toHaveValue('2')
  await confirmation.getByRole('button', { name: 'Choisir', exact: true }).click()
  const traces = page.getByRole('dialog', { name: 'Numéros de série', exact: true })
  for (const index of [1, 2]) {
    await traces.getByRole('button', { name: 'Ajouter un numéro', exact: true }).click()
    await traces.getByRole('combobox', { name: `Identité ${index}`, exact: true }).click()
    await page.getByRole('option', { name: `BL-UI-S${index} · 1 u`, exact: true }).click()
  }
  await traces.getByRole('button', { name: 'Appliquer', exact: true }).click()
  await confirmation.screenshot({ path: '/private/tmp/horizon-delivery-serial-partial.png' })
  await confirmation.getByRole('button', { name: 'Confirmer', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  const deliveryId = new URL(page.url()).pathname.split('/').at(-1)!
  const delivered = await api(`horizon/inventory/operations/${deliveryId}`)
  expect(delivered.lines[0].traces).toHaveLength(2)
  expect(delivered.lines[0].planned_quantity).toBe(4)
  expect(delivered.lines[0].quantity).toBe(2)
  const remainder = await api(`horizon/inventory/operations?kind=OUT&status=draft&sales_quote=${quote.id}`)
  expect(remainder.totalItems).toBe(1)
  expect(remainder.items[0].lines[0].quantity).toBe(2)
  expect(remainder.items[0].lines[0].traces).toHaveLength(0)
})
