import { test, expect } from '@playwright/test'

test('Devis et commande : colonnes alignées et cadre arrondi après changement de statut', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const token = await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '')
  const api = async (path: string, data?: object) => {
    const response = await request.fetch(`http://127.0.0.1:18090/api/${path}`, { method: data ? 'POST' : 'GET', headers: { Authorization: token }, ...(data ? { data } : {}) })
    expect(response.status(), await response.text()).toBe(200)
    return response.json()
  }
  const company = await api('collections/contacts_companies/records', { name: 'Client alignement', active: true })
  const session = await api('collections/core_users/auth-refresh', {}), stages = await api('collections/crm_stages/records')
  const opportunity = await api('horizon/crm/save', { creation_key: crypto.randomUUID(), input: { title: 'Affaire alignement', company: company.id, contact: '', owner: session.record.id, stage: stages.items[0].id, type: 'direct', estimated_value: 1000, estimated_cost: 0, currency: 'EUR', probability: 0, expected_date: '', description: '', status: 'open' } })
  let quote = await api('horizon/sales/quotes/save', { creation_key: crypto.randomUUID(), input: { opportunity: opportunity.id, title: 'Colonnes du devis', quote_date: '2026-10-15', valid_until: '2026-11-15', lines: [{ description: 'Produit 1', quantity: 1, unit: 'u', unit_price: 10, unit_cost: 5 }, { kind: 'spacer', description: '', quantity: 0, unit: '', unit_price: 0, unit_cost: 0 }, { description: 'Produit 2', quantity: 2, unit: 'u', unit_price: 20, unit_cost: 8 }, { kind: 'subtitle', description: 'Sous-titre', quantity: 0, unit: '', unit_price: 0 }, { kind: 'note', description: 'Note', quantity: 0, unit: '', unit_price: 0 }] } })
  const table = page.locator('.quote-edit-table')
  async function geometry() {
    return table.evaluate((element) => {
      const headers = [...element.querySelectorAll('thead th')], cells = [...element.querySelectorAll('tbody tr:first-child > td')]
      return headers.map((header, index) => {
        const cell = cells[index]!, handle = header.querySelector('.quote-column-resizer')!, headStyle = getComputedStyle(header), bodyStyle = getComputedStyle(cell), handleStyle = getComputedStyle(handle)
        return { label: header.getAttribute('aria-label'), headRight: header.getBoundingClientRect().right, bodyRight: cell.getBoundingClientRect().right, headBorder: headStyle.borderRightWidth, bodyBorder: bodyStyle.borderRightWidth, handleBorder: handleStyle.borderRightWidth }
      })
    })
  }
  async function aligned() {
    const preview = page.locator('.h-table-drag-preview')
    await expect(preview).toBeEmpty()
    await expect(preview).toHaveCSS('border-top-width', '0px')
    await expect(preview).toHaveCSS('box-shadow', 'none')
    expect((await preview.boundingBox())?.height ?? 0).toBe(0)
    if ((await page.viewportSize())!.width >= 1000) await expect.poll(() => table.evaluate((element) => element.getBoundingClientRect().width - element.closest('[data-table-viewport]')!.clientWidth)).toBeLessThan(0.5)
    await expect(table.locator('tbody tr.quote-row--spacer')).toHaveCount(1)
    await expect(table.locator('tbody tr.quote-row--subtitle')).toHaveCount(1)
    await expect(table.locator('tbody tr.quote-row--note')).toHaveCount(1)
    const headerRights = await table.locator('thead th').evaluateAll((headers) => headers.map((header) => header.getBoundingClientRect().right))
    for (const row of await table.locator('tbody tr').all()) {
      const cells = await row.evaluate((element) => [...element.querySelectorAll('td')].map((cell) => ({ span: cell.colSpan, right: cell.getBoundingClientRect().right, border: getComputedStyle(cell).borderRightWidth })))
      expect(cells).toHaveLength(headerRights.length)
      for (const [index, cell] of cells.entries()) {
        expect(cell.span).toBe(1)
        expect(Math.abs(cell.right - headerRights[index]!)).toBeLessThan(0.1)
        expect(cell.border).toBe(index === cells.length - 1 ? '0px' : '1px')
      }
    }
    const columns = await geometry()
    for (const column of columns) {
      expect(Math.abs(column.headRight - column.bodyRight), column.label || '').toBeLessThan(0.1)
      expect(column.headBorder, column.label || '').toBe(column.bodyBorder)
      expect(column.handleBorder, column.label || '').toBe('0px')
    }
  }
  await page.goto('/settings/ux?tab=tables')
  await expect(page.locator('.ux-controls summary')).toHaveText(['Densité des tableaux', 'En-têtes et bordures', 'Lignes du tableau', 'Suivi des commandes'])
  await page.getByRole('button', { name: 'Tout déplier', exact: true }).click()
  await page.getByLabel('Code hexadécimal : Fond des en-têtes · clair', { exact: true }).fill('#FDECF4')
  await page.getByLabel('Code hexadécimal : Texte et pictogrammes · clair', { exact: true }).fill('#70334D')
  const previewHeaders = page.locator('.ux-preview th.h-table-tracking-cell')
  await expect(previewHeaders).toHaveCount(4)
  for (const header of await previewHeaders.all()) { await expect(header).toHaveCSS('background-color', 'rgb(253, 236, 244)'); await expect(header.locator('svg')).toHaveCSS('color', 'rgb(112, 51, 77)') }
  await expect(page.locator('.ux-preview td.h-table-tracking-cell').first()).not.toHaveCSS('background-color', 'rgb(253, 236, 244)')
  await page.screenshot({ path: '/private/tmp/horizon-tracking-header-settings-light.png', fullPage: true })
  await page.getByRole('button', { name: 'Sombre', exact: true }).click()
  await page.getByLabel('Code hexadécimal : Fond des en-têtes · sombre', { exact: true }).fill('#3B2938')
  await page.getByLabel('Code hexadécimal : Texte et pictogrammes · sombre', { exact: true }).fill('#FFC1DE')
  for (const header of await previewHeaders.all()) await expect(header).toHaveCSS('background-color', 'rgb(59, 41, 56)')
  await page.screenshot({ path: '/private/tmp/horizon-tracking-header-settings-dark.png', fullPage: true })
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  await page.reload()
  await page.getByRole('button', { name: 'Tout déplier', exact: true }).click()
  await expect(page.getByLabel('Code hexadécimal : Fond des en-têtes · clair', { exact: true })).toHaveValue('#FDECF4')
  await page.goto(`/sales/quotes/${quote.id}`)
  await expect(table.locator('tbody tr')).toHaveCount(5)
  await page.getByLabel('Description ligne 4', { exact: true }).fill('')
  await page.getByLabel('Description ligne 5', { exact: true }).fill('')
  await table.screenshot({ path: '/private/tmp/horizon-quote-columns-20261015.png' })
  await aligned()
  const widthBefore = (await table.locator('thead th').first().boundingBox())!.width
  await table.getByRole('button', { name: 'Redimensionner #', exact: true }).press('ArrowRight')
  await expect.poll(async () => (await table.locator('thead th').first().boundingBox())!.width).toBeGreaterThan(widthBefore)
  await aligned()
  quote = await api('horizon/sales/quotes/finalize', { id: quote.id, updated: quote.updated })
  await api('horizon/sales/quotes/confirm', { id: quote.id, updated: quote.updated, customer_order_number: 'CLIENT-ALIGNEMENT', reservations: [] })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Lignes de la commande (5)', exact: true })).toBeVisible()
  await expect(table.getByRole('columnheader', { name: 'Achats', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /(?:Replier|Déplier) les colonnes de suivi/ })).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: 'Suivi de la commande', exact: true })).toHaveCount(0)
  for (const label of ['Achats', 'Réceptions', 'Livraisons', 'Facturé']) {
    const header = table.getByRole('columnheader', { name: label, exact: true })
    await expect(header.locator('.h-table-tracking-caption')).toHaveText('')
    await expect(header.locator('.h-table-tracking-caption')).toHaveAttribute('title', label)
    await expect(header.locator('.h-table-tracking-caption svg')).toBeVisible()
    await expect(header).toHaveCSS('background-color', 'rgb(253, 236, 244)')
    await expect(header.locator('.h-table-tracking-caption svg')).toHaveCSS('color', 'rgb(112, 51, 77)')
  }
  await expect(table.getByRole('columnheader', { name: 'Livraisons', exact: true }).locator('.lucide-truck')).toBeVisible()
  await expect(table.locator('.quote-purchase-status').first()).toHaveText('0/1')
  await expect(table.locator('.quote-purchase-status').first()).not.toHaveCSS('background-color', 'rgb(253, 236, 244)')
  await aligned()
  await expect(table).toHaveCSS('border-radius', '6px')
  await expect(table).toHaveCSS('border-collapse', 'separate')
  await table.screenshot({ path: '/private/tmp/horizon-order-columns-20261015.png' })
  await page.screenshot({ path: '/private/tmp/horizon-order-no-gray-line-light.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  await aligned()
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  for (const header of await table.locator('th.h-table-tracking-cell').all()) { await expect(header).toHaveCSS('background-color', 'rgb(59, 41, 56)'); await expect(header.locator('.h-table-tracking-caption svg')).toHaveCSS('color', 'rgb(255, 193, 222)') }
  await table.screenshot({ path: '/private/tmp/horizon-order-columns-dark-20261015.png' })
  await page.screenshot({ path: '/private/tmp/horizon-order-no-gray-line-dark.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await aligned()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-order-columns-mobile-20261015.png', fullPage: true })
  await page.setViewportSize({ width: 1600, height: 1000 })
  await expect(page.getByRole('button', { name: 'Modifier la commande', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Actions de la fiche', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Modifier la commande', exact: true }).click()
  await expect(page.getByLabel('Quantité ligne 1', { exact: true })).toBeEnabled()
  await page.getByLabel('Quantité ligne 1', { exact: true }).fill('3')
  for (const label of ['Achats', 'Réceptions', 'Livraisons', 'Facturé']) await expect(table.getByRole('columnheader', { name: label, exact: true })).toBeVisible()
  await aligned()
})

test('Colonnes : montants contenus, déplacement borné à droite et ajustement des largeurs enregistrées', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const token = await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '')
  const api = async (path: string, data?: object) => {
    const response = await request.fetch(`http://127.0.0.1:18090/api/${path}`, { method: data ? 'POST' : 'GET', headers: { Authorization: token }, ...(data ? { data } : {}) })
    expect(response.status(), await response.text()).toBe(200)
    return response.json()
  }
  const session = await api('collections/core_users/auth-refresh', {}), stages = await api('collections/crm_stages/records')
  const company = await api('collections/contacts_companies/records', { name: 'Client débordement', active: true })
  const opportunity = await api('horizon/crm/save', { creation_key: crypto.randomUUID(), input: { title: 'Affaire colonnes', company: company.id, contact: '', owner: session.record.id, stage: stages.items[0].id, type: 'direct', estimated_value: 1000, estimated_cost: 0, currency: 'EUR', probability: 0, expected_date: '', description: '', status: 'open' } })
  const quote = await api('horizon/sales/quotes/save', { creation_key: crypto.randomUUID(), input: { opportunity: opportunity.id, title: 'Montants des titres', quote_date: '2026-10-16', valid_until: '2026-11-16', lines: [{ kind: 'section', description: 'Section avec total', show_total: true, quantity: 0, unit: '', unit_price: 0 }, { description: 'Produit', quantity: 1, unit: 'u', unit_price: 9839.33, unit_cost: 100 }, { kind: 'section', description: 'Option avec total', show_total: true, is_option: true, quantity: 0, unit: '', unit_price: 0 }, { description: 'Produit option', quantity: 1, unit: 'u', unit_price: 12345678.99, is_option: true }] } })
  await page.evaluate((id) => localStorage.setItem(`horizon:quote-columns:${id}`, JSON.stringify({ description: 1000, line_total: 82, is_option: 42, actions: 58 })), session.record.id)
  await page.goto(`/sales/quotes/${quote.id}`)
  const table = page.locator('.quote-edit-table'), totals = table.locator('.quote-total-value, .quote-section-amount strong')
  await expect(totals).toHaveCount(4)
  async function contained() {
    for (const total of await totals.all()) {
      await expect(total).toHaveCSS('white-space', 'nowrap')
      await expect(total).toHaveAttribute('title', /€/)
      expect(await total.evaluate((element) => element.getBoundingClientRect().right <= element.closest('td')!.getBoundingClientRect().right + 0.5)).toBe(true)
    }
    for (const total of await totals.all()) expect(await total.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    for (const input of await table.locator('.h-amount-input input').all()) expect(await input.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  }
  await contained()
  const precisePrice = page.getByLabel('Prix unitaire ligne 2', { exact: true })
  await precisePrice.fill('11111111,111111')
  await precisePrice.blur()
  await expect(precisePrice).toHaveValue(/11.*111.*111,111111.*€/)
  await contained()
  await table.screenshot({ path: '/private/tmp/horizon-column-overflow-light.png' })
  expect(await table.evaluate((element) => element.getBoundingClientRect().width - element.closest('[data-table-viewport]')!.clientWidth)).toBeLessThan(1)
  await page.evaluate((id) => localStorage.setItem(`horizon:quote-columns:${id}`, JSON.stringify({ line_total: 140, is_option: 80, actions: 80 })), session.record.id)
  await page.reload({ waitUntil: 'networkidle' })
  await expect(totals).toHaveCount(4)
  const headers = table.locator('thead th')
  const geometry = () => headers.evaluateAll((elements) => elements.map((element) => ({ label: element.getAttribute('aria-label'), left: element.getBoundingClientRect().left, width: element.getBoundingClientRect().width })))
  const before = await geometry()
  const totalHeader = table.getByRole('columnheader', { name: 'PTV', exact: true }), handle = totalHeader.getByRole('button', { name: 'Redimensionner PTV', exact: true })
  await handle.scrollIntoViewIfNeeded()
  const position = (await handle.boundingBox())!
  await page.mouse.move(position.x + position.width / 2, position.y + position.height / 2)
  await page.mouse.down()
  await page.mouse.move(position.x + position.width / 2 + 180, position.y + position.height / 2, { steps: 12 })
  await page.mouse.up()
  const after = await geometry(), totalIndex = before.findIndex((column) => column.label === 'PTV')
  expect(after[totalIndex]!.width - before[totalIndex]!.width).toBeLessThan(60)
  expect(after[totalIndex]!.width - before[totalIndex]!.width).toBeGreaterThan(1)
  for (let index = 0; index < totalIndex; index++) expect(Math.abs(after[index]!.width - before[index]!.width)).toBeLessThan(3)
  expect(await table.evaluate((element) => element.getBoundingClientRect().width - element.closest('[data-table-viewport]')!.clientWidth)).toBeLessThan(1)
  await page.reload({ waitUntil: 'networkidle' })
  await expect.poll(async () => Math.abs((await totalHeader.boundingBox())!.width - after[totalIndex]!.width)).toBeLessThan(3)
  const widthBeforeLeft = (await totalHeader.boundingBox())!.width
  await handle.press('ArrowLeft')
  await expect.poll(async () => (await totalHeader.boundingBox())!.width).toBeLessThanOrEqual(widthBeforeLeft + 1)
  expect(await table.evaluate((element) => element.getBoundingClientRect().width - element.closest('[data-table-viewport]')!.clientWidth)).toBeLessThan(1)
  const beforeCompression = await geometry(), leftStart = (await handle.boundingBox())!
  await page.mouse.move(leftStart.x + leftStart.width / 2, leftStart.y + leftStart.height / 2)
  await page.mouse.down()
  await page.mouse.move(leftStart.x + leftStart.width / 2 - 220, leftStart.y + leftStart.height / 2, { steps: 12 })
  await page.mouse.up()
  const compressed = await geometry()
  expect(compressed[totalIndex]!.width).toBeGreaterThan(140)
  await contained()
  expect(beforeCompression[totalIndex - 1]!.width - compressed[totalIndex - 1]!.width).toBeGreaterThan(5)
  expect(compressed[totalIndex + 1]!.width - beforeCompression[totalIndex + 1]!.width).toBeGreaterThan(200)
  expect(Math.abs(compressed[totalIndex + 2]!.width - beforeCompression[totalIndex + 2]!.width)).toBeLessThan(3)
  expect(await table.evaluate((element) => element.getBoundingClientRect().width - element.closest('[data-table-viewport]')!.clientWidth)).toBeLessThan(1)
  await page.reload({ waitUntil: 'networkidle' })
  await expect.poll(async () => Math.abs((await totalHeader.boundingBox())!.width - compressed[totalIndex]!.width)).toBeLessThan(3)
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await table.screenshot({ path: '/private/tmp/horizon-column-resize-dark.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await expect.poll(() => table.evaluate((element) => element.getBoundingClientRect().width > element.closest('[data-table-viewport]')!.clientWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-column-resize-mobile.png', fullPage: true })
})
