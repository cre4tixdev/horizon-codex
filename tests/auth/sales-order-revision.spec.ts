test('Commande : édition, récapitulatif, annulation et révisions sans modifier le devis accepté', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const headers = { Authorization: await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '') }
  const api = async (path: string, data?: object) => {
    const response = await request.fetch(`http://127.0.0.1:18090/api/${path}`, { method: data ? 'POST' : 'GET', headers, ...(data ? { data } : {}) })
    expect(response.status(), await response.text()).toBe(200); return response.json()
  }
  const company = await api('collections/contacts_companies/records', { name: 'Client révision', active: true })
  const stages = await api('collections/crm_stages/records'), session = await api('collections/core_users/auth-refresh', {})
  const opportunity = await api('horizon/crm/save', { creation_key: crypto.randomUUID(), input: { title: 'Affaire révision', company: company.id, contact: '', owner: session.record.id, stage: stages.items[0].id, type: 'direct', estimated_value: 1000, estimated_cost: 0, currency: 'EUR', probability: 0, expected_date: '', description: '', status: 'open' } })
  let quote = await api('horizon/sales/quotes/save', { creation_key: crypto.randomUUID(), input: { opportunity: opportunity.id, title: 'Devis accepté original', quote_date: '2026-10-15', valid_until: '2026-11-15', lines: [{ description: 'Prestation initiale', quantity: 4, unit: 'u', unit_price: 100, unit_cost: 50 }] } })
  quote = await api('horizon/sales/quotes/finalize', { id: quote.id, updated: quote.updated })
  quote = await api('horizon/sales/quotes/confirm', { id: quote.id, updated: quote.updated, customer_order_number: 'CLIENT-REV', reservations: [] })
  await page.goto(`/sales/quotes/${quote.id}`)
  await expect(page.getByLabel('Description ligne 1', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Modifier la commande', exact: true }).click()
  await page.getByLabel('Description ligne 1', { exact: true }).fill('Modification abandonnée')
  await page.getByRole('button', { name: 'Annuler les modifications', exact: true }).click()
  await expect(page.getByLabel('Description ligne 1', { exact: true })).toHaveValue('Prestation initiale')
  await expect(page.getByLabel('Description ligne 1', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Modifier la commande', exact: true }).click()
  await page.getByLabel('Titre du devis', { exact: true }).fill('Commande révisée')
  await page.getByLabel('Quantité ligne 1', { exact: true }).fill('6')
  await page.getByRole('button', { name: 'Dupliquer ligne 1', exact: true }).click()
  await page.getByLabel('Description ligne 2', { exact: true }).fill('Complément')
  await page.getByLabel('Quantité ligne 2', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Enregistrer les modifications de commande', exact: true })
  await expect(dialog.getByText('Nouvelle ligne', { exact: true })).toBeVisible()
  await dialog.screenshot({ path: '/private/tmp/horizon-order-revision-preview-light.png' })
  await dialog.getByRole('button', { name: 'Reprendre l’édition', exact: true }).click()
  await expect(page.getByLabel('Description ligne 2', { exact: true })).toHaveValue('Complément')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirmer les modifications', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByLabel('Description ligne 2', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Révisions (1)', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Quantité ligne 1', { exact: true })).toHaveValue('6')
  await expect(page.getByLabel('Description ligne 2', { exact: true })).toHaveValue('Complément')
  const original = await api(`collections/sales_quotes/records/${quote.id}`)
  expect(original.title).toBe('Devis accepté original'); expect(original.subtotal).toBe(400)
  const listed = await api('horizon/sales/quotes?q=Commande%20révisée&status=accepted')
  expect(listed.items.some((item: { id: string }) => item.id === quote.id)).toBe(true)
  await page.getByRole('button', { name: 'Révisions (1)', exact: true }).click()
  const history = page.getByRole('dialog', { name: 'Révisions de la commande', exact: true })
  await expect(history.getByText('Nouvelle ligne', { exact: true })).toBeVisible()
  await history.getByRole('button', { name: 'Fermer', exact: true }).last().click()
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.getByRole('button', { name: 'Modifier la commande', exact: true }).click()
  await page.getByLabel('Quantité ligne 1', { exact: true }).fill('5')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Confirmer les modifications', exact: true })).toBeEnabled()
  await dialog.screenshot({ path: '/private/tmp/horizon-order-revision-preview-dark.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/private/tmp/horizon-order-revision-preview-mobile.png', fullPage: true })
  await dialog.getByRole('button', { name: 'Reprendre l’édition', exact: true }).click()
  await expect(page.getByLabel('Quantité ligne 1', { exact: true })).toHaveValue('5')
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.getByRole('button', { name: 'Annuler les modifications', exact: true }).click()
  await api('collections/contacts_addresses/records', { company: company.id, type: 'billing', line1: 'Rue Test', city: 'Paris', postal_code: '75001', country: 'FR', is_primary: true })
  const settings = await api('horizon/billing/settings')
  settings.issuer = { ...settings.issuer, name: 'CVS Engineering Recette', address: 'Rue de test', city: 'Paris', postal_code: '75001', country: 'FR', siret: '00000000000000', vat_number: 'FR00000000000', late_payment_notice: 'Selon conditions contractuelles.' }
  await api('horizon/billing/settings', settings)
  const prepared = await api('horizon/billing/documents/prepare', { kind: 'customer', source_type: 'order', source_ids: [quote.id], mode: 'standard', deposit_percent: 30 })
  const draft = await api('horizon/billing/documents/save', { kind: 'customer', creation_key: crypto.randomUUID(), input: { ...prepared, supplier_invoice_number: '', invoice_date: '2026-10-15', due_date: '2026-11-15', service_date: '2026-10-15', currency: 'EUR', notes: '', discrepancy_reason: '', source_invoice: '', template_id: '', schedules: [] } })
  const invoice = await api('horizon/billing/documents/transition', { kind: 'customer', id: draft.id, updated: draft.updated, action: 'validate' })
  await page.reload()
  await page.getByRole('button', { name: 'Modifier la commande', exact: true }).click()
  await page.getByLabel('Quantité ligne 1', { exact: true }).fill('5')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(dialog.getByText(/Préparer un avoir brouillon sur/)).toBeVisible()
  await dialog.screenshot({ path: '/private/tmp/horizon-order-revision-credit-preview.png' })
  await dialog.getByRole('button', { name: 'Confirmer les modifications', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Révisions (2)', exact: true })).toBeVisible()
  const credits = await api(`horizon/billing/documents?kind=customer_credit&source_order=${quote.id}`)
  expect(credits.items).toHaveLength(1)
  expect(credits.items[0].status).toBe('draft')
  expect(credits.items[0].total).toBe(120)
  const preserved = await api(`horizon/billing/record/customer/${invoice.id}`)
  expect(preserved.total).toBe(invoice.total)
  await page.getByRole('button', { name: 'Révisions (2)', exact: true }).click()
  const address = page.url()
  await history.getByRole('button', { name: 'Ouvrir l’avoir brouillon', exact: true }).click()
  const creditPopup = page.getByRole('dialog', { name: 'Avoir', exact: true })
  await expect(creditPopup).toBeVisible()
  await expect(creditPopup.getByLabel('Description ligne 1', { exact: true })).toBeVisible()
  await expect(page).toHaveURL(address)
  expect(page.context().pages()).toHaveLength(1)
  await creditPopup.getByLabel('Description ligne 1', { exact: true }).fill('Saisie non enregistrée')
  await creditPopup.getByRole('button', { name: 'Fermer', exact: true }).first().click()
  await expect(page.getByRole('alertdialog', { name: 'Fermer sans enregistrer ?', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Abandonner les changements', exact: true }).click()
  await expect(history).toBeVisible()
})


