import { writeFileSync } from 'node:fs'
import { test, expect } from '@playwright/test'
import { defaultLabelLayout, printableWidth } from '../../src/modules/documents/schemas/templates'

async function login(page: import('@playwright/test').Page, identity = 'erp-admin@local.invalid') {
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill(identity)
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
}

test('Étiquettes : bouton du produit, format réel, modèle publié et impression isolée', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const auth = await page.request.post('http://127.0.0.1:18090/api/collections/core_users/auth-with-password', { data: { identity: 'erp-admin@local.invalid', password: 'Local-Horizon-test-only-2026!' } })
  const headers = { Authorization: (await auth.json()).token as string }
  async function post(path: string, data: unknown) {
    const result = await page.request.post(`http://127.0.0.1:18090/api/${path}`, { headers, data })
    expect(result.ok(), await result.text()).toBeTruthy()
    return result.json() as Promise<{ id: string; updated: string }>
  }
  const choices = await (await page.request.get('http://127.0.0.1:18090/api/horizon/inventory/choices', { headers })).json() as { categories: { id: string; code: string }[]; units: { id: string; code: string }[] }
  const product = await post('horizon/inventory/products/save', { creation_key: 'label-product-browser-0001', input: { sku: 'BNC-12G-SDI', name: 'Fiche BNC vidéo 12G', description: '', category: choices.categories.find((item) => item.code === 'equipment')!.id, base_unit: choices.units.find((item) => item.code === 'u')!.id, kind: 'equipment', sale_enabled: true, purchase_enabled: true, stock_policy: 'stocked', replenishment_policy: 'manual', tracking: 'none', manufacturer: 'NEUTRIK', manufacturer_ref: '', barcode: 'BNC-12G-SDI', variant_group: '', reference_cost: 12, sale_currency: 'EUR', offers: [] } })
  const model = defaultLabelLayout(); model.pageSize = { width: 85, height: 40 }
  for (const block of model.blocks) block.width = Math.min(block.width, printableWidth(model) - block.x)
  const template = await post('horizon/documents/templates/save', { name: 'Étiquette BNC', document_type: 'product_label', content_json: model })
  await post('horizon/documents/templates/publish', { id: template.id, updated: template.updated })
  await login(page)
  await page.goto(`/inventory/products/${product.id}`)
  const barcodeInput = page.getByLabel('Code-barres', { exact: true })
  const button = page.getByRole('button', { name: 'Imprimer l’étiquette produit', exact: true })
  const inputBounds = (await barcodeInput.boundingBox())!, buttonBounds = (await button.boundingBox())!
  expect(buttonBounds.x).toBeGreaterThan(inputBounds.x + inputBounds.width - 1)
  expect(Math.abs(buttonBounds.y - inputBounds.y)).toBeLessThan(2)
  await button.click()
  const dialog = page.getByRole('dialog', { name: 'Étiquette produit', exact: true })
  await expect(dialog.locator('.document-preview-format')).toContainText('95 × 28 mm')
  const frame = page.frameLocator('iframe[title="Aperçu de l’étiquette produit"]')
  await expect(frame.locator('.pagedjs_page')).toHaveCount(1)
  await expect(frame.locator('.document-barcode svg')).toBeVisible()
  await expect(frame.getByText('NEUTRIK', { exact: true })).toBeVisible()
  await expect(frame.getByText('Fiche BNC vidéo 12G', { exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Imprimer', exact: true })).toBeEnabled()
  await frame.locator('body').evaluate(() => { window.print = () => { document.body.dataset.printed = 'true' } })
  await dialog.getByRole('button', { name: 'Imprimer', exact: true }).click()
  await expect(frame.locator('body')).toHaveAttribute('data-printed', 'true')
  const printable = await frame.locator('html').evaluate((node) => { const copy = node.cloneNode(true) as HTMLElement; copy.querySelectorAll('script,template').forEach((element) => element.remove()); return '<!doctype html>' + copy.outerHTML })
  const paper = await page.context().newPage()
  await paper.setContent(printable)
  await paper.evaluate(() => document.fonts.ready)
  const bytes = await paper.pdf({ preferCSSPageSize: true, printBackground: true })
  writeFileSync('/private/tmp/horizon-label-printed.pdf', bytes)
  const pdfText = bytes.toString('latin1'), media = pdfText.match(/\/MediaBox \[0 0 ([\d.]+) ([\d.]+)\]/)!
  expect(pdfText.match(/\/Type \/Page\b/g)).toHaveLength(1)
  expect(Number(media[1])).toBeCloseTo(95 * 72 / 25.4, 0)
  expect(Number(media[2])).toBeCloseTo(28 * 72 / 25.4, 0)
  await paper.close()
  await dialog.getByRole('combobox', { name: 'Modèle de l’étiquette', exact: true }).click()
  await page.getByRole('option', { name: 'Étiquette BNC · v1', exact: true }).click()
  await expect(dialog.locator('.document-preview-format')).toContainText('85 × 40 mm')
  await expect(frame.locator('.pagedjs_page')).toHaveCount(1)
  await expect(frame.locator('.document-barcode svg')).toBeVisible()
  await page.screenshot({ path: '/private/tmp/horizon-product-label-preview.png' })
  await dialog.getByRole('button', { name: 'Fermer', exact: true }).click()
  await page.goto('/settings/documents?tab=formats')
  await page.getByRole('button', { name: 'Nouveau format', exact: true }).click()
  const formatDialog = page.getByRole('dialog', { name: 'Nouveau format', exact: true })
  await formatDialog.getByLabel('Nom du format', { exact: true }).fill('Étiquette connecteurs')
  await formatDialog.getByLabel('Largeur (mm)', { exact: true }).fill('85')
  await formatDialog.getByLabel('Hauteur (mm)', { exact: true }).fill('40')
  await formatDialog.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(formatDialog).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: 'Étiquette connecteurs' })).toContainText('85')
  await page.goto('/settings/documents/new')
  await page.locator('.studio-section[data-section="page-format"] > summary').click()
  await page.getByRole('combobox', { name: 'Type de pièce', exact: true }).click()
  await page.getByRole('option', { name: 'Étiquette produit', exact: true }).click()
  await expect(page.locator('.studio-page-dimension-width')).toHaveText('95 mm')
  await page.getByRole('combobox', { name: 'Format du papier', exact: true }).click()
  await page.getByRole('option', { name: 'Étiquette connecteurs · 85 × 40 mm', exact: true }).click()
  await expect(page.getByLabel('Largeur de page (mm)', { exact: true })).toHaveValue('85')
  await expect(page.getByLabel('Hauteur de page (mm)', { exact: true })).toHaveValue('40')
  await expect(page.locator('.studio-page-dimension-width')).toHaveText('85 mm')
  await expect(page.locator('.studio-page-dimension-height')).toHaveText('40 mm')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/settings\/documents\/(?!new)/)
  await page.screenshot({ path: '/private/tmp/horizon-label-studio.png' })
  await page.getByRole('button', { name: 'Menu utilisateur', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Se déconnecter', exact: true }).click()
  await login(page, 'catalog-viewer@local.invalid')
  await page.goto(`/inventory/products/${product.id}`)
  await expect(page.getByLabel('Code-barres', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Imprimer l’étiquette produit', exact: true }).click()
  await expect(page.frameLocator('iframe[title="Aperçu de l’étiquette produit"]').locator('.document-barcode svg')).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Imprimer', exact: true })).toBeEnabled()
  expect(errors).toEqual([])
})
