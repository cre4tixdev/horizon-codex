import { test, expect } from '@playwright/test'

test('Sous-titre et bordures : devis, modèle, sauvegarde et aperçu paginé', async ({ page, request, browser }) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const token = await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '')
  const api = async (path: string, data?: object) => {
    const response = await request.fetch(`http://127.0.0.1:18090/api/${path}`, { method: data ? 'POST' : 'GET', headers: { Authorization: token }, ...(data ? { data } : {}) })
    expect(response.status(), await response.text()).toBe(200)
    return response.json()
  }
  const company = await api('collections/contacts_companies/records', { name: 'Client sous-titres', active: true })
  const session = await api('collections/core_users/auth-refresh', {}), stages = await api('collections/crm_stages/records')
  const opportunity = await api('horizon/crm/save', { creation_key: crypto.randomUUID(), input: { title: 'Affaire sous-titres', company: company.id, contact: '', owner: session.record.id, stage: stages.items[0].id, type: 'direct', estimated_value: 1000, estimated_cost: 0, currency: 'EUR', probability: 0, expected_date: '', description: '', status: 'open' } })
  const quote = await api('horizon/sales/quotes/save', { creation_key: crypto.randomUUID(), input: { opportunity: opportunity.id, title: 'Devis bordures et sous-titre', quote_date: '2026-10-13', valid_until: '2026-11-13', lines: [{ kind: 'section', description: 'Titre principal', show_total: true }, { kind: 'subsection', description: 'Titre secondaire' }, { kind: 'subsection3', description: 'Titre troisième' }, { description: 'Article', quantity: 2, unit: 'u', unit_price: 10, unit_cost: 5 }] } })
  await page.goto(`/sales/quotes/${quote.id}`)
  const additions = page.locator('.quote-line-additions')
  await expect(additions.getByRole('button', { name: 'Sous-titre', exact: true })).toBeVisible()
  const labels = await additions.getByRole('button').allTextContents()
  expect(labels.indexOf('Sous-titre')).toBe(labels.indexOf('Titre niveau 3') + 1)
  expect(labels.indexOf('Note')).toBe(labels.indexOf('Sous-titre') + 1)
  await additions.getByRole('button', { name: 'Sous-titre', exact: true }).click()
  await page.getByLabel('Description ligne 5', { exact: true }).fill('Sous-titre de recette')
  await expect(page.getByLabel('Quantité ligne 5', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  const updated = await api(`horizon/sales/quotes/${quote.id}`)
  expect(updated.lines[4].kind).toBe('subtitle')
  expect(updated.subtotal).toBe(20)
  await page.goto('/settings/documents/new')
  await page.getByRole('button', { name: 'Sélectionner Tableau', exact: true }).click()
  const styles = page.locator('[data-section=table-headings]')
  await styles.locator('summary').click()
  await styles.getByRole('button', { name: 'Titre 1', exact: true }).click()
  await expect(styles.getByRole('button', { name: 'Bordure bas', exact: true })).toHaveAttribute('aria-pressed', 'true')
  for (const name of ['haut', 'gauche', 'droite', 'bas']) await styles.getByRole('button', { name: `Bordure ${name}`, exact: true }).click()
  await styles.getByRole('textbox', { name: 'Code hexadécimal : Couleur de la bordure', exact: true }).fill('#123456')
  await styles.getByLabel('Épaisseur de la bordure (px)', { exact: true }).fill('2.5')
  await styles.getByRole('button', { name: 'Sous-titre', exact: true }).click()
  await expect(styles.getByRole('button', { name: 'Gras', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(styles.getByRole('button', { name: 'Italique', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await styles.getByRole('button', { name: 'Bordure bas', exact: true }).click()
  await styles.getByRole('textbox', { name: 'Code hexadécimal : Couleur de la bordure', exact: true }).fill('#F52F96')
  await styles.getByLabel('Épaisseur de la bordure (px)', { exact: true }).fill('1.5')
  await styles.getByLabel('Taille du texte (px)', { exact: true }).fill('14')
  await page.screenshot({ path: '/private/tmp/horizon-subtitle-studio-light.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page).toHaveURL(/settings\/documents\/(?!new)/)
  const templateId = new URL(page.url()).pathname.split('/').at(-1)!
  await page.reload()
  await page.getByRole('button', { name: 'Sélectionner Tableau', exact: true }).click()
  await styles.getByRole('button', { name: 'Sous-titre', exact: true }).click()
  await expect(styles.getByLabel('Épaisseur de la bordure (px)', { exact: true })).toHaveValue('1.5')
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-subtitle-studio-dark.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Passer en mode clair', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(styles.getByLabel('Épaisseur de la bordure (px)', { exact: true })).toBeVisible()
  await styles.getByLabel('Épaisseur de la bordure (px)', { exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/private/tmp/horizon-subtitle-studio-mobile.png', animations: 'disabled' })
  await page.setViewportSize({ width: 1600, height: 1000 })
  const template = await api(`horizon/documents/templates/${templateId}`)
  const preview = await api('horizon/documents/preview', { quote_id: quote.id, content_json: template.content_json, format: 'html' })
  await page.getByRole('button', { name: 'Aperçu / PDF', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Aperçu du devis', exact: true })
  await dialog.getByRole('combobox', { name: 'Devis de l’aperçu', exact: true }).click()
  await page.getByRole('option', { name: new RegExp(quote.title) }).click()
  const frame = page.frameLocator('iframe[title="Aperçu du devis enregistré"]')
  const title = frame.locator('.pagedjs_page .lines td').filter({ hasText: /^Titre principal/ }).first()
  const subtitle = frame.locator('.pagedjs_page .lines td').filter({ hasText: /^Sous-titre de recette$/ }).first()
  await expect(subtitle).toHaveCSS('font-size', '14px')
  await expect(subtitle).toHaveCSS('border-bottom-color', 'rgb(245, 47, 150)')
  await expect(title).toBeVisible()
  await expect(title).toHaveAttribute('style', /border-top:2\.5px/)
  await expect(title).toHaveCSS('border-top-style', 'solid')
  await expect(title).toHaveCSS('border-left-color', 'rgb(18, 52, 86)')
  await expect(title).toHaveCSS('border-bottom-style', 'none')
  await dialog.screenshot({ path: '/private/tmp/horizon-subtitle-html-preview.png', animations: 'disabled' })
  // A real Chromium PDF of the preview HTML; Gotenberg print transport is tested server-side.
  const printPage = await browser.newPage()
  await printPage.setContent(preview.html)
  await printPage.pdf({ path: '/private/tmp/horizon-subtitle-chromium.pdf', preferCSSPageSize: true, printBackground: true })
  await printPage.close()
})
