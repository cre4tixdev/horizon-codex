import { test, expect } from '@playwright/test'
import { defaultLayout } from '../../src/modules/documents/schemas/templates'

test('Devis : conserver les lignes vides, leur ordre et les espaces du document', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const token = await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '')
  const api = async (path: string, data?: object) => {
    const response = await request.fetch(`http://127.0.0.1:18090/api/${path}`, { method: data ? 'POST' : 'GET', headers: { Authorization: token }, ...(data ? { data } : {}) })
    expect(response.status(), await response.text()).toBe(200)
    return response.json()
  }
  const company = await api('collections/contacts_companies/records', { name: 'Client espacements', active: true })
  const session = await api('collections/core_users/auth-refresh', {}), stages = await api('collections/crm_stages/records')
  const opportunity = await api('horizon/crm/save', { creation_key: crypto.randomUUID(), input: { title: 'Affaire espacements', company: company.id, contact: '', owner: session.record.id, stage: stages.items[0].id, type: 'direct', estimated_value: 1000, estimated_cost: 0, currency: 'EUR', probability: 0, expected_date: '', description: '', status: 'open' } })
  const quote = await api('horizon/sales/quotes/save', { creation_key: crypto.randomUUID(), input: { opportunity: opportunity.id, title: 'Devis avec espaces', quote_date: '2026-10-13', valid_until: '2026-11-13', lines: [{ description: 'Avant espace', quantity: 1, unit: 'u', unit_price: 10, unit_cost: 5 }] } })
  await page.goto(`/sales/quotes/${quote.id}`)
  await page.getByRole('button', { name: 'Ajouter une ligne', exact: true }).click()
  await page.getByRole('button', { name: 'Ajouter une ligne', exact: true }).click()
  await page.getByRole('button', { name: 'Ajouter une ligne', exact: true }).click()
  await page.getByLabel('Description ligne 4', { exact: true }).fill('Après espace')
  await page.getByLabel('Prix unitaire ligne 4', { exact: true }).fill('5')
  await page.getByRole('button', { name: 'Note', exact: true }).click()
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.locator('.quote-edit-table tbody tr')).toHaveCount(5)
  await expect(page.getByLabel('Description ligne 2', { exact: true })).toBeEmpty()
  await expect(page.getByLabel('Description ligne 3', { exact: true })).toBeEmpty()
  await expect(page.getByLabel('Quantité ligne 2', { exact: true })).toHaveCount(0)
  const saved = await api(`horizon/sales/quotes/${quote.id}`)
  expect(saved.lines.map((line: { kind: string }) => line.kind)).toEqual(['item', 'spacer', 'spacer', 'item', 'spacer'])
  expect(saved.subtotal).toBe(15)
  await page.getByRole('button', { name: 'Dupliquer ligne 2', exact: true }).click()
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  expect((await api(`horizon/sales/quotes/${quote.id}`)).lines).toHaveLength(6)
  const model = await api('horizon/documents/templates/save', { name: 'Espaces de devis', content_json: defaultLayout() })
  await api('horizon/documents/templates/publish', { id: model.id, updated: model.updated })
  await page.getByRole('button', { name: 'Aperçu', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Aperçu du devis', exact: true })
  const selector = dialog.getByRole('combobox', { name: 'Modèle du devis', exact: true })
  if (!(await selector.textContent())?.includes('Espaces de devis')) {
    await selector.click()
    await page.getByRole('option', { name: 'Espaces de devis · v1', exact: true }).click()
  }
  const frame = page.frameLocator('iframe[title="Aperçu du devis enregistré"]')
  await expect(frame.locator('.pagedjs_page .lines tr.spacer')).toHaveCount(4)
  const blank = frame.locator('.pagedjs_page .lines tr.spacer td').first()
  await expect(blank).toHaveCSS('height', '24px')
  await expect(blank).toHaveCSS('border-bottom-style', 'none')
  await dialog.screenshot({ path: '/private/tmp/horizon-quote-spacers-preview.png', animations: 'disabled' })
  await dialog.getByRole('button', { name: 'Fermer', exact: true }).click()
  await page.getByLabel('Description ligne 2', { exact: true }).fill('Texte ajouté à la place du vide')
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enregistrer', exact: true })).toBeDisabled()
  expect((await api(`horizon/sales/quotes/${quote.id}`)).lines[1].kind).toBe('note')
})
