import { expect, test } from '@playwright/test'

test('Achats réunit DA et BC, cartes filtrantes et création de commande à droite', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const token = await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '')
  for (const title of ['DA accueil à traiter', 'Autre DA accueil']) {
    const response = await request.post('http://127.0.0.1:18090/api/horizon/purchasing/requests/save', {
      headers: { Authorization: token }, data: { creation_key: crypto.randomUUID(), input: { title, document_date: '2026-10-12', currency: 'EUR', lines: [] } },
    })
    expect(response.status(), await response.text()).toBe(200)
  }
  const supplierResponse = await request.post('http://127.0.0.1:18090/api/collections/contacts_companies/records', { headers: { Authorization: token }, data: { name: 'Fournisseur accueil', active: true } })
  expect(supplierResponse.status(), await supplierResponse.text()).toBe(200)
  const supplier = await supplierResponse.json()
  const roleResponse = await request.post('http://127.0.0.1:18090/api/collections/contacts_company_roles/records', { headers: { Authorization: token }, data: { company: supplier.id, role: 'supplier', active: true } })
  expect(roleResponse.status(), await roleResponse.text()).toBe(200)
  const orderResponse = await request.post('http://127.0.0.1:18090/api/horizon/purchasing/orders/save', { headers: { Authorization: token }, data: { creation_key: crypto.randomUUID(), input: { title: 'BC accueil à traiter', supplier: supplier.id, document_date: '2026-10-12', currency: 'EUR', lines: [] } } })
  expect(orderResponse.status(), await orderResponse.text()).toBe(200)
  const order = await orderResponse.json()
  await page.getByRole('navigation', { name: 'Navigation principale', exact: true }).getByRole('link', { name: 'Achats', exact: true }).click()
  await expect(page).toHaveURL('/purchasing?status=pending')
  const cards = page.getByRole('region', { name: 'Synthèse des achats' })
  await expect(cards.locator('.contact-summary-card')).toHaveCount(4)
  await expect(cards.getByRole('link', { name: 'Filtrer les achats : DA en attente', exact: true }).locator('strong')).toHaveText('2')
  await expect(page.locator('.h-data-table tbody tr')).toHaveCount(3)
  await expect(page.locator('.h-data-table tbody').getByText('DA', { exact: true })).toHaveCount(2)
  await expect(page.locator('.h-data-table tbody').getByText('BC', { exact: true })).toHaveCount(1)
  await cards.getByRole('link', { name: 'Filtrer les achats : Bons de commande', exact: true }).click()
  await expect(page).toHaveURL('/purchasing?status=orders')
  await expect(page.locator('.h-data-table tbody tr')).toHaveCount(1)
  await expect(page.getByRole('link', { name: `Ouvrir ${order.number}`, exact: true })).toHaveAttribute('href', `/purchasing/orders/${order.id}`)
  await page.getByRole('link', { name: `Ouvrir ${order.number}`, exact: true }).click()
  await page.getByRole('navigation', { name: 'Fil d’Ariane', exact: true }).getByRole('link', { name: 'Achats', exact: true }).click()
  await expect(page).toHaveURL('/purchasing?status=orders')
  await cards.getByRole('link', { name: 'Filtrer les achats : DA en attente', exact: true }).click()
  await expect(page).toHaveURL('/purchasing?status=requests')
  await expect(page.locator('.h-data-table tbody tr')).toHaveCount(2)
  await expect(page.locator('.h-data-table tbody').getByText('BC', { exact: true })).toHaveCount(0)
  const newOrder = page.locator('.page-breadcrumb-record-actions').getByRole('link', { name: 'Nouvelle commande', exact: true })
  await expect(newOrder).toHaveAttribute('href', '/purchasing/orders/new')
  await page.goto('/purchasing?q=à traiter&group=supplier_name&page=2')
  await expect(page).toHaveURL(/purchasing\?q=.*group=supplier_name.*page=2.*status=pending/)
  await cards.getByRole('link', { name: 'Filtrer les achats : Brouillon', exact: true }).click()
  await expect(page).toHaveURL(/status=draft/)
  expect(new URL(page.url()).searchParams.get('q')).toBe('à traiter')
  expect(new URL(page.url()).searchParams.get('group')).toBe('supplier_name')
  expect(new URL(page.url()).searchParams.has('page')).toBe(false)
  await expect(cards.getByRole('link', { name: 'Filtrer les achats : DA en attente', exact: true }).locator('strong')).toHaveText('1')
  await cards.getByRole('link', { name: 'Filtrer les achats : DA en attente', exact: true }).click()
  await expect(page).toHaveURL(/status=requests/)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Achats', exact: true })).toBeVisible()
  await page.goto('/purchasing?q=à traiter&group=supplier_name&status=pending')
  await expect(page.locator('.h-data-table tbody tr')).toHaveCount(2)
  await page.screenshot({ path: '/private/tmp/horizon-purchasing-home-light.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-purchasing-home-dark.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Passer en mode clair', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(newOrder).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-purchasing-home-mobile.png', animations: 'disabled' })
  await newOrder.click()
  await expect(page).toHaveURL('/purchasing/orders/new')
  await expect(page.getByRole('heading', { name: 'Nouvelle commande fournisseur', exact: true })).toBeVisible()
})
