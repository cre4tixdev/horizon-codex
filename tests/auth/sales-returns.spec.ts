import { test, expect } from '@playwright/test'

test('Commande : livraison nette et compteur de retours compact', async ({ page, request }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('erp-admin@local.invalid')
  await page.getByLabel('Mot de passe', { exact: true }).fill('Local-Horizon-test-only-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL('/')
  const headers = { Authorization: await page.evaluate(() => sessionStorage.getItem('horizon.auth.token') || '') }
  const api = async (path: string, data?: object) => {
    const response = await request.fetch(`http://127.0.0.1:18090/api/${path}`, { method: data ? 'POST' : 'GET', headers, ...(data ? { data } : {}) })
    expect(response.status(), await response.text()).toBe(200)
    return response.json()
  }
  const company = await api('collections/contacts_companies/records', { name: 'Client retours', active: true })
  const stages = await api('collections/crm_stages/records'), session = await api('collections/core_users/auth-refresh', {})
  const opportunity = await api('horizon/crm/save', { creation_key: crypto.randomUUID(), input: { title: 'Retours équipement', company: company.id, contact: '', owner: session.record.id, stage: stages.items[0].id, type: 'direct', estimated_value: 1000, estimated_cost: 0, currency: 'EUR', probability: 0, expected_date: '', description: '', status: 'open' } })
  const choices = await api('horizon/inventory/choices'), categories = await api('horizon/inventory/categories')
  const brand = await api('horizon/inventory/brands/create', { name: 'Marque retour' })
  const product = await api('horizon/inventory/products/save', { creation_key: crypto.randomUUID(), input: { sku: 'RETURN-UI', name: 'Équipement retourné', description: '', manufacturer_ref: '', barcode: '', variant_group: '', category: categories.items[0].id, kind: 'equipment', base_unit: choices.units.find((unit: { code: string }) => unit.code === 'u').id, brand: brand.id, stock_policy: 'stocked', replenishment_policy: 'manual', tracking: 'none', sale_enabled: true, purchase_enabled: true, sale_currency: 'EUR', reference_cost: 50, cost_override: true, offers: [] } })
  let quote = await api('horizon/sales/quotes/save', { creation_key: crypto.randomUUID(), input: { opportunity: opportunity.id, title: 'Commande avec retour', quote_date: '2026-10-15', valid_until: '2026-11-15', lines: [{ product: product.id, description: product.name, quantity: 4, unit: 'u', unit_price: 60, unit_cost: 50 }] } })
  quote = await api('horizon/sales/quotes/finalize', { id: quote.id, updated: quote.updated })
  quote = await api('horizon/sales/quotes/confirm', { id: quote.id, updated: quote.updated, customer_order_number: 'CLIENT-RETOUR', reservations: [] })
  const stock = await api('horizon/inventory/operations/choices')
  const warehouse = stock.warehouses.find((item: { code: string }) => item.code === 'MEU').id
  const location = stock.locations.find((item: { warehouse: string; code: string }) => item.warehouse === warehouse && item.code === 'STOCK').id
  const input = { kind: 'IN', warehouse, destination_warehouse: '', title: 'Réception équipement', opportunity: '', purchase_order: '', sales_quote: '', origin: '', destination: '', reason: 'Test retours', notes: '', document_date: '2026-10-15', planned_date: '', inventory_mode: 'cycle', dropship: false, scrap: false, scope: [], lines: [{ id: 'line-1', product: product.id, quantity: 4, from_location: '', to_location: location, source_line: '', counted: null }] }
  const receipt = await api('horizon/inventory/operations/save', { creation_key: crypto.randomUUID(), input })
  await api('horizon/inventory/operations/transition', { id: receipt.id, updated: receipt.updated, action: 'validate' })
  const draft = await api('horizon/inventory/operations/prepare-delivery', { sales_quote: quote.id, warehouse })
  const delivery = await api('horizon/inventory/operations/transition', { id: draft.id, updated: draft.updated, action: 'validate' })
  await page.goto(`/sales/quotes/${quote.id}`)
  const full = page.getByRole('link', { name: 'Livraisons ligne 1 : 4 livrés, 0 retournés, 4 chez le client', exact: true })
  await expect(full).toHaveAttribute('data-covered', 'true')
  await expect(full.locator('.quote-return-count')).toHaveCount(0)
  const returned = await api('horizon/inventory/operations/save', { creation_key: crypto.randomUUID(), input: { ...input, kind: 'RET', origin: delivery.id, lines: [{ ...input.lines[0], quantity: 1, origin_line: delivery.lines[0].id }] } })
  await api('horizon/inventory/operations/transition', { id: returned.id, updated: returned.updated, action: 'validate' })
  await page.goto(`/sales/quotes/${quote.id}`)
  const link = page.getByRole('link', { name: 'Livraisons ligne 1 : 4 livrés, 1 retourné, 3 chez le client', exact: true })
  await expect(link).toHaveAttribute('title', '4 livrés · 1 retourné · 3 chez le client')
  await expect(link).toContainText('3/4')
  await expect(link.locator('.quote-return-count')).toHaveText('1')
  await expect(link).toHaveAttribute('data-covered', 'false')
  await link.scrollIntoViewIfNeeded()
  await page.locator('.quote-edit-table').screenshot({ path: '/private/tmp/horizon-sales-return-light.png' })
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.locator('.quote-edit-table').screenshot({ path: '/private/tmp/horizon-sales-return-dark.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await link.scrollIntoViewIfNeeded()
  await expect(link).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-sales-return-mobile.png', fullPage: true })
  // Un lien natif reste actif dans le fieldset de consultation désactivé.
  await link.click({ force: true })
  await expect(page).toHaveURL(new RegExp(`inventory/operations\\?sales_quote=${quote.id}`))
  await expect(page.getByText(returned.number, { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto(`/sales/quotes/${quote.id}`)
  await page.getByRole('button', { name: 'Préparer la livraison', exact: true }).click()
  await expect(page).toHaveURL(/inventory\/operations\/[a-z0-9]+$/)
  const replacement = await api(`horizon/inventory/operations/${page.url().split('/').pop()}`)
  expect(replacement.lines).toHaveLength(1)
  expect(replacement.lines[0].quantity).toBe(1)
  expect(replacement.readiness.required).toBe(1)
  expect(replacement.readiness.ready).toBe(1)
  await page.screenshot({ path: '/private/tmp/horizon-redelivery-draft.png', fullPage: true })
  await api('horizon/inventory/operations/transition', { id: replacement.id, updated: replacement.updated, action: 'validate' })
  await page.goto(`/sales/quotes/${quote.id}`)
  const redelivered = page.getByRole('link', { name: 'Livraisons ligne 1 : 5 livrés, 1 retourné, 4 chez le client', exact: true })
  await expect(redelivered).toContainText('4/4')
  await expect(redelivered.locator('.quote-return-count')).toHaveText('1')
  await expect(redelivered).toHaveAttribute('data-covered', 'true')
  await expect(page.getByRole('button', { name: 'Préparer la livraison', exact: true })).toHaveCount(0)
  await page.locator('.quote-edit-table').screenshot({ path: '/private/tmp/horizon-redelivery-complete.png' })
})
