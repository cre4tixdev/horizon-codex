  await page.getByRole('tab', { name: 'Analyse', exact: true }).click()
  const recordTabs = page.locator('.contact-record-navigation [role=tab]')
  await expect(recordTabs.locator('svg[aria-hidden=true]')).toHaveCount(await recordTabs.count())
  const analysis = page.locator('.affair-analysis')
  await expect(analysis.getByRole('heading', { name: `Analyse de l’affaire ${opp.opportunity_number}` })).toBeVisible()
  await expect(analysis.locator('.analysis-indicators')).toContainText('600,00 €')
  await expect(analysis.locator('.analysis-indicators')).toContainText('440,00 €')
  await expect(analysis.locator('.analysis-indicators > .contact-panel')).toHaveCount(5)
  await expect(analysis.locator('.analysis-histogram')).toHaveCount(5)
  const baselinePositions = await analysis.locator('.analysis-histogram svg').evaluateAll((elements) => elements.map((element) => element.getBoundingClientRect().bottom))
  expect(Math.max(...baselinePositions) - Math.min(...baselinePositions)).toBeLessThan(1)
  expect((await analysis.locator('.analysis-indicator').first().boundingBox())!.height).toBeLessThan(195)
  const orderCard = analysis.locator('.analysis-indicator').filter({ has: page.getByRole('heading', { name: 'Commande Client', exact: true }) })
  await expect(orderCard.getByRole('img')).toHaveCount(1)
  await expect(orderCard.locator('.analysis-histogram-value')).toHaveCount(0)
  await expect(orderCard.locator('.analysis-estimate')).toContainText('1 000,00 €')
  await expect(orderCard.locator('.analysis-histogram-reference')).toHaveAttribute('data-exceeded', 'false')
  await expect(analysis.locator('.analysis-indicators')).not.toContainText('Coût des heures et frais à raccorder')
  await expect(analysis.locator('.analysis-histogram-label, .analysis-histogram-target')).toHaveCount(0)
  await expect(orderCard.getByRole('img', { name: 'Commandé : 600,00 €', exact: true })).toBeVisible()
  const hoursCard = analysis.locator('.analysis-indicator').filter({ has: page.getByRole('heading', { name: 'Heures', exact: true }) })
  await expect(hoursCard.locator('.analysis-histogram-group')).toHaveCount(2)
  for (const label of ['BE', 'PROD']) await expect(hoursCard.getByText(label, { exact: true })).toBeVisible()
  await expect(hoursCard.getByRole('img')).toHaveCount(2)
  await expect(hoursCard.locator('.analysis-histogram-value')).toHaveCount(0)
  await expect(hoursCard.getByRole('img', { name: 'BE · Réalisées : —', exact: true })).toBeVisible()
  for (const name of ['Commande Client', 'Achats', 'Livraison', 'Heures', 'Marge à date']) await expect(analysis.locator('.analysis-indicators').getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(analysis.getByRole('heading', { name: 'Synthèse par commande et coûts communs', exact: true })).toBeVisible()
  await expect(analysis).not.toContainText('Les heures de l’affaire et de ses commandes sont consolidées une seule fois.')
  await expect(analysis.getByRole('heading', { name: 'Heures BE et PROD', exact: true })).toBeVisible()
  for (const label of ['BE · Prévu', 'BE · Réalisé', 'PROD · Prévu', 'PROD · Réalisé']) await expect(analysis.getByRole('columnheader', { name: label, exact: true })).toBeVisible()
  await expect(analysis.locator('.analysis-hours')).toContainText('La source TimeReport n’est pas encore disponible')
  await expect(analysis.getByRole('table').first().getByRole('row').filter({ hasText: first.quote_number })).toContainText('200,00 €')
  await expect(analysis.getByRole('table').first().getByRole('row').filter({ hasText: second.quote_number })).toContainText('400,00 €')
  await page.screenshot({ path: '/private/tmp/horizon-analysis-affair.png', fullPage: true })
  await page.getByRole('tab', { name: 'Informations', exact: true }).click()
  await page.getByLabel('Titre', { exact: true }).fill('Affaire Analyse éditée')
  await page.getByRole('tab', { name: 'Analyse', exact: true }).click()
  await page.getByRole('tab', { name: 'Informations', exact: true }).click()
  await expect(page.getByLabel('Titre', { exact: true })).toHaveValue('Affaire Analyse éditée')
  await page.goto(`/sales/quotes/${first.id}`)
  await page.getByRole('tab', { name: 'Analyse', exact: true }).click()
  await expect(analysis.locator('.analysis-indicators')).toContainText('200,00 €')
  await expect(analysis.locator('.analysis-indicators')).not.toContainText('600,00 €')
  await analysis.getByRole('link', { name: 'Analyse globale', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Analyse', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('link', { name: 'Analyse des affaires', exact: true }).click()
  const search = page.getByRole('searchbox', { name: 'Rechercher une affaire à analyser', exact: true })
  await search.fill('Affaire Analyse')
  await expect(page.locator('.h-data-table')).toContainText('600,00 €')
  await page.reload()
  await expect(search).toHaveValue('Affaire Analyse')
  await page.getByRole('link', { name: new RegExp(opp.opportunity_number + '.*Affaire Analyse') }).click()
  await expect(analysis).toContainText('600,00 €')
  // An estimate below the confirmed revenue shows only the excess in red.
  await page.route('**/api/horizon/analysis/report?opportunity=*', async (route) => {
    const response = await route.fetch(), data = await response.json()
    data.totals.financial.estimated_revenue = 300
    await route.fulfill({ response, json: data })
  })
  await page.reload()
  await expect(analysis.locator('.analysis-indicator').first().locator('.analysis-histogram-overflow')).toHaveCount(1)
  await expect(analysis.locator('.analysis-indicator').first().locator('.analysis-histogram-reference')).toHaveCount(1)
  await expect(analysis.locator('.analysis-indicator').first().locator('.analysis-histogram-reference')).toHaveAttribute('data-exceeded', 'true')
  await page.unroute('**/api/horizon/analysis/report?opportunity=*')
  await page.route('**/api/horizon/analysis/report?opportunity=*', async (route) => {
    const response = await route.fetch(), data = await response.json()
    data.totals.financial.estimated_revenue = 2345844.54
    data.totals.financial.revenue = 94547.25
    await route.fulfill({ response, json: data })
  })
  await page.reload()
  const targetValue = analysis.locator('.analysis-indicator').first().locator('.analysis-estimate')
  await expect(targetValue).toContainText('2 345 844,54')
  const targetBounds = (await targetValue.boundingBox())!, cardBounds = (await analysis.locator('.analysis-indicator').first().boundingBox())!
  expect(targetBounds.x + targetBounds.width).toBeLessThanOrEqual(cardBounds.x + cardBounds.width)
  await page.screenshot({ path: '/private/tmp/horizon-analysis-large-values.png', fullPage: true })
  await page.unroute('**/api/horizon/analysis/report?opportunity=*')
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-analysis-dark.png', fullPage: true })
  await page.setViewportSize({ width: 600, height: 900 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-analysis-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/settings/users')
  await page.getByRole('button', { name: 'Nouvel utilisateur', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Nouvel utilisateur', exact: true })
  await editor.getByLabel('Nom affiché', { exact: true }).fill('Analyste opérationnel')
  await editor.getByLabel('E-mail de connexion', { exact: true }).fill('analysis-viewer@local.invalid')
  await editor.getByLabel('Mot de passe initial', { exact: true }).fill('Local-Analysis-Test-2026!')
