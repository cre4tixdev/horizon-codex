import { expect, test } from '@playwright/test'

test('sections : repli individuel au clavier, navigation et préférence restaurée', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  const navigation = page.getByRole('navigation', { name: 'Navigation principale', exact: true })
  const contacts = navigation.getByRole('link', { name: 'Contacts', exact: true })
  await navigation.getByRole('button', { name: 'Déplier Contacts', exact: true }).click()
  await expect(navigation.getByRole('link', { name: 'Clients', exact: true })).toBeVisible()
  const toggle = navigation.getByRole('button', { name: 'Replier la section Activité', exact: true })
  await page.mouse.move(600, 400)
  await expect(toggle.locator('svg')).toHaveCSS('opacity', '0')
  await toggle.hover(); await expect(toggle.locator('svg')).toHaveCSS('opacity', '1')
  await page.mouse.move(600, 400)
  await expect(toggle.locator('svg')).toHaveCSS('opacity', '0')
  const controls = await toggle.getAttribute('aria-controls')
  expect(controls).toBeTruthy()
  await toggle.focus(); await page.keyboard.press('Tab'); await page.keyboard.press('Shift+Tab')
  await expect(toggle).toBeFocused(); await expect(toggle.locator('svg')).toHaveCSS('opacity', '1'); await page.keyboard.press('Enter')
  await expect(navigation.getByRole('button', { name: 'Déplier la section Activité', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(navigation.getByRole('button', { name: 'Déplier la section Activité', exact: true }).locator('.sidebar-group-count')).toHaveText('· 7')
  await expect(contacts).toBeHidden()
  await expect(navigation.getByRole('link', { name: 'Calendrier', exact: true })).toBeVisible()
  await page.reload()
  await expect(contacts).toBeHidden()
  await navigation.getByRole('button', { name: 'Déplier la section Activité', exact: true }).click()
  await expect(toggle.locator('.sidebar-group-count')).toHaveCount(0)
  await contacts.click(); await expect(page).toHaveURL('/contacts')
  await expect(contacts).toHaveAttribute('aria-current', 'page')
  await navigation.getByRole('button', { name: 'Replier la section Ressources humaines', exact: true }).click()
  await page.mouse.move(600, 400)
  await page.screenshot({ path: '/private/tmp/horizon-sidebar-sections-light.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Passer en mode sombre', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/horizon-sidebar-sections-dark.png', animations: 'disabled' })
})

test('sections : action globale et accès aux modules en mode pictogrammes et mobile', async ({ page }) => {
  await page.goto('/')
  const navigation = page.getByRole('navigation', { name: 'Navigation principale', exact: true })
  await navigation.getByRole('button', { name: 'Replier la section Activité', exact: true }).click()
  const action = page.getByRole('button', { name: 'Replier toutes les sections', exact: true })
  await expect(action).toHaveAttribute('title', 'Replier toutes les sections')
  await expect(action).toHaveText('')
  const logoBounds = await page.getByRole('button', { name: 'Ouvrir les modules Horizon', exact: true }).boundingBox()
  const actionBounds = await action.boundingBox()
  expect(actionBounds!.x).toBeGreaterThanOrEqual(logoBounds!.x + logoBounds!.width)
  expect(Math.abs(actionBounds!.y + actionBounds!.height / 2 - logoBounds!.y - logoBounds!.height / 2)).toBeLessThan(1)
  await action.click()
  await expect(navigation.getByRole('link')).toHaveCount(0)
  await expect(navigation.locator('.sidebar-group-toggle[aria-expanded=false]')).toHaveCount(5)
  await page.screenshot({ path: '/private/tmp/horizon-sidebar-sections-folded.png', animations: 'disabled' })
  await page.reload()
  await expect(navigation.getByRole('link')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Déplier toutes les sections', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Réduire la navigation', exact: true }).click()
  await expect(navigation.getByRole('link', { name: 'Contacts', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Déplier toutes les sections', exact: true })).toBeHidden()
  await page.getByRole('button', { name: 'Développer la navigation', exact: true }).click()
  await expect(navigation.getByRole('link')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(navigation.getByRole('link', { name: 'Contacts', exact: true })).toBeVisible()
  await expect(navigation.getByRole('link', { name: 'Dashboard', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/private/tmp/horizon-sidebar-sections-mobile.png', animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Déplier toutes les sections', exact: true }).click()
  await expect(navigation.locator('.sidebar-group-toggle[aria-expanded=true]')).toHaveCount(5)
  await expect(navigation.getByRole('link', { name: 'Contacts', exact: true })).toBeVisible()
})
